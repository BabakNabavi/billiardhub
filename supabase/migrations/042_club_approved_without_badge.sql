-- «تأیید بدونِ تیکِ آبی» برای باشگاه‌ها
--
-- تا امروز `verificationStatus` دو کارِ جدا را با یک مقدار انجام
-- می‌داد: `verified` هم یعنی «در فهرستِ عمومی دیده شو» و هم یعنی
-- «تیکِ آبی بگیر». نتیجه‌اش این بود که باشگاهی که مدرکی آپلود نکرده
-- یا مدارکش هنوز بررسی نشده، یا باید تیکِ آبیِ نداشته را می‌گرفت یا
-- اصلاً در سایت دیده نمی‌شد. راهِ سومی نبود.
--
-- مقدارِ تازه‌ی `approved` همان راهِ سوم است:
--   · در فهرستِ عمومی دیده می‌شود (کارتش می‌رود توی بخشِ باشگاه‌ها)
--   · تیکِ آبی نمی‌گیرد، چون مدرکی تأیید نشده
--
-- هیچ ردیفی این‌جا عوض نمی‌شود؛ فقط مقدارِ تازه مجاز می‌شود. باشگاه‌های
-- فعلی دقیقاً همان‌جا که هستند می‌مانند.
-- ═══════════════════════════════════════════════════════════════

-- قید دوباره ساخته می‌شود چون CHECK قابلِ ALTER نیست. اجرای دوباره‌ی
-- این فایل بی‌خطر است.
ALTER TABLE public.clubs DROP CONSTRAINT IF EXISTS clubs_verification_chk;

ALTER TABLE public.clubs ADD CONSTRAINT clubs_verification_chk
  CHECK ("verificationStatus" IN
    ('pending', 'verified', 'approved', 'rejected', 'unverified'));

-- فهرستِ عمومی حالا دو مقدار را می‌پذیرد؛ همان ایندکسِ ترکیبی
-- (isActive, verificationStatus) هنوز درست کار می‌کند و لازم نیست
-- چیزی اضافه شود.

-- ── بررسی ──
-- انتظار: پنج مقدارِ مجاز، و توزیعِ فعلیِ باشگاه‌ها دست‌نخورده.
SELECT "verificationStatus", count(*)
  FROM public.clubs
 GROUP BY "verificationStatus"
 ORDER BY 2 DESC;
