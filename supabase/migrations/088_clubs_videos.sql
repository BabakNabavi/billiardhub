-- ─────────────────────────────────────────────────────────────
-- ویدیوهای گالریِ باشگاه.
--
-- گالریِ باشگاه به کامپوننتِ مشترکِ پروفایل‌ها منتقل شد و آن‌جا سه تب
-- دارد: تصاویر، ویدیوها، آلبوم‌ها. باشگاه تنها نقشی بود که ستونی
-- برای ویدیوهای گالری نداشت، پس تبِ ویدیو برایش پنهان می‌ماند.
--
-- ⚠️ چرا نامش `videos` نیست: ستونِ `videos` از قبل وجود دارد و
-- `text[]` است — ویدیوی معرفیِ خودِ باشگاه که در `/clubs/new` آپلود
-- می‌شود. برداشتن یا تغییرِ شکلش یعنی شکستنِ آن مسیر. پس ستونِ تازه
-- کنارش می‌نشیند و آن یکی دست‌نخورده می‌ماند.
--
-- شکل دقیقاً همان چیزی است که پروفایل‌ها در jsonb نگه می‌دارند:
--   [{ id, url, thumbnail, title, duration, album? }]
--
-- پیش‌فرض `[]` است نه NULL: کد روی آرایه حلقه می‌زند و NULL یعنی
-- گاردِ اضافه در هر نقطه‌ی مصرف.
-- ─────────────────────────────────────────────────────────────

ALTER TABLE public.clubs
  ADD COLUMN IF NOT EXISTS "galleryVideos" jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN public.clubs."galleryVideos" IS
  'ویدیوهای گالری باشگاه — [{id,url,thumbnail,title,duration,album?}]';

-- توضیحِ ستونِ قدیمی هم صریح می‌شود تا دوباره با این اشتباه نشود.
-- ⚠️ داخلِ گارد، چون جدولِ `clubs` در این پوشه ساخته نشده و ممکن است
-- در محیطی که از صفر ساخته می‌شود این ستون هنوز نباشد.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'clubs' AND column_name = 'videos'
  ) THEN
    COMMENT ON COLUMN public.clubs.videos IS
      'ویدیوی معرفی باشگاه (text[] از /clubs/new) — نه گالری';
  END IF;
END $$;

-- ⚠️ بدونِ این، PostgREST تا ری‌استارتِ بعدی ستون را نمی‌شناسد و مسیرِ
-- PUT بی‌صدا کنارش می‌گذارد (همان شاخه‌ی PGRST204): پاسخ ۲۰۰ می‌آید و
-- ویدیوی تازه‌آپلودشده بی‌هیچ خطایی ناپدید می‌شود.
NOTIFY pgrst, 'reload schema';
