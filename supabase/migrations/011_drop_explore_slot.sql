-- ═══════════════════════════════════════════════════════════════════
-- 011 — حذفِ جایگاهِ «explore»
--
-- جایگاهِ زیر «بیشتر در بیلیارد هاب کاوش کن» و جایگاهِ بالای فوتر روی
-- صفحه‌ی اصلی عملاً یک‌جا می‌افتادند و دو بنرِ پشتِ‌هم نشان می‌دادند.
-- جایگاهِ بالای فوتر می‌ماند چون در همه‌ی صفحات دیده می‌شود.
-- ═══════════════════════════════════════════════════════════════════

DELETE FROM public.ad_placements WHERE slot_key = 'explore';
DELETE FROM public.ad_slots      WHERE key      = 'explore';

/* درخواست‌های تبلیغی که این جایگاه را انتخاب کرده بودند بی‌جایگاه می‌شوند،
   نه حذف — تماسشان هنوز ارزش دارد. */
UPDATE public.ad_requests SET slot_key = NULL WHERE slot_key = 'explore';
