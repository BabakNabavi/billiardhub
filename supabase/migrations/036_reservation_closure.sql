-- ─────────────────────────────────────────────────────────────
-- بستنِ رزرو — سطحِ میز، و انتقالِ بستنِ موقت به سرور
--
-- ── ۱) بستنِ رزروِ یک میز ──
-- تا امروز راهی نبود که یک میزِ خاص (در تعمیر، اجاره‌ی بلندمدت،
-- خرابیِ ماهوت) از رزروِ آنلاین بیرون بماند بدون اینکه حذف شود.
-- `isActive` این کار را نمی‌کند: آن یعنی «میز اصلاً وجود ندارد» و
-- میز را از همه‌جای سیستم — از جمله گزارش‌ها — برمی‌دارد.
--
-- ── ۲) بستنِ موقتِ رزروِ باشگاه ──
-- دکمه‌های «بستن برای ۳/۶/۱۲ ساعت» مقدارشان را فقط در
-- localStorageی مرورگرِ خودِ باشگاه‌دار می‌نوشتند. یعنی:
--   • سرور از آن بی‌خبر بود و رزرو را واقعاً نمی‌بست
--   • هیچ بازدیدکننده‌ی دیگری آن را نمی‌دید و می‌توانست رزرو کند
--   • و در مرورگرِ خودِ باشگاه‌دار، کلِ صفحه‌ی رزرو بسته می‌شد
-- یعنی دقیقاً برعکسِ چیزی که باید. حالا روی خودِ باشگاه ذخیره می‌شود.
--
-- NULL یعنی «بسته نیست». `infinity` یعنی «همیشه بسته».
-- ─────────────────────────────────────────────────────────────

ALTER TABLE tables ADD COLUMN IF NOT EXISTS "reservationClosed" boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN tables."reservationClosed" IS
  'میز از رزروِ آنلاین بیرون است ولی همچنان ثبت‌شده می‌ماند. با isActive فرق دارد.';

ALTER TABLE clubs ADD COLUMN IF NOT EXISTS "reserveClosedUntil" timestamptz;

COMMENT ON COLUMN clubs."reserveClosedUntil" IS
  'بستنِ موقتِ رزروِ آنلاین تا این لحظه. NULL = باز. infinity = همیشه بسته.';

-- فهرستِ میزهای قابلِ رزرو در هر بار بازکردنِ صفحه‌ی رزرو خوانده می‌شود
CREATE INDEX IF NOT EXISTS tables_club_bookable_idx
  ON tables ("clubId") WHERE "reservationClosed" = false;
