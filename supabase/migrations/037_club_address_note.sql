-- ─────────────────────────────────────────────────────────────
-- توضیحات آدرس
--
-- آدرسِ برگشته از استعلامِ کد پستی رسمی و دقیق است، ولی همیشه کافی
-- نیست: «طبقه‌ی سوم، واحد ۷»، «ورودی از کوچه‌ی پشتی»، «روبه‌روی
-- داروخانه». تا امروز باشگاه‌دار مجبور بود این‌ها را داخلِ خودِ آدرس
-- بنویسد و آدرسِ استعلام‌شده را خراب کند.
--
-- پس آدرس دست‌نخورده و فقط‌خواندنی می‌ماند، و این ستون جای افزوده‌های
-- خودِ باشگاه‌دار است.
-- ─────────────────────────────────────────────────────────────

ALTER TABLE clubs ADD COLUMN IF NOT EXISTS "addressNote" text;

COMMENT ON COLUMN clubs."addressNote" IS
  'توضیحات تکمیلی آدرس — نوشته‌ی خودِ باشگاه‌دار، جدا از آدرسِ استعلام‌شده.';
