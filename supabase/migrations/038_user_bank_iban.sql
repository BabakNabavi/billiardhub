-- شبای کارت کاربر
--
-- کارت بانکی کاربر مقصدِ بازگشتِ وجهِ رزروِ لغوشده است. تا امروز فقط
-- شماره‌ی کارت و نام دارنده ذخیره می‌شد، ولی بازگشتِ وجه در نهایت به
-- شبا انجام می‌شود نه به کارت — و شبا همان لحظه‌ی استعلام در دسترس
-- است. نگه‌داشتنش یعنی دیگر لازم نیست هنگام بازپرداخت دوباره استعلام
-- بگیریم (اعتبار مصرف کند و ممکن است سرویس در دسترس نباشد).
--
-- نام بانک ستون نمی‌خواهد: از پیشوندِ خودِ شبا مشتق می‌شود.
-- ─────────────────────────────────────────────────────────────

ALTER TABLE users ADD COLUMN IF NOT EXISTS bank_iban text;

COMMENT ON COLUMN users.bank_iban IS
  'شبای کارتِ کاربر — از استعلامِ CardToIban. مقصدِ واقعیِ بازگشتِ وجه.';
