-- ─────────────────────────────────────────────────────────────
-- ۱۰۴ — کاملِ‌کردنِ ردِ ممیزی: رویدادهای احراز هویت + ایندکسِ خواندن
--
-- ── مسئله ──
-- `audit_logs` از ۰۰۱ هست و ۱۲۷ نوع رویداد در آن نوشته می‌شود، ولی:
--
--   ۱) تنها ایندکسش `(entity_type, entity_id, created_at)` است —
--      یعنی برای «آخرین رویدادها» یا «هرچه این کاربر کرده» یا
--      «همه‌ی LOGIN_FAILها» باید کلِ جدول اسکن شود. تا امروز مهم
--      نبود چون هیچ‌کس نمی‌خواندش؛ با آمدنِ صفحه‌ی /admin/logs مهم
--      می‌شود.
--
--   ۲) ستونِ `user_agent` ندارد. برای رویدادِ مالی لازم نبود، برای
--      رویدادِ امنیتی هست: «همین حساب، همین دقیقه، از دو مرورگرِ
--      متفاوت» بدونِ آن دیده نمی‌شود.
--
--   ۳) تلاشِ ناموفقِ ورود هیچ تاریخچه‌ای ندارد. `login_attempts`
--      شمارنده‌ی قفل است نه ژورنال: یک ردیف به ازای هر
--      (scope, subject) که مدام به‌روز می‌شود. یعنی «این حساب دیشب
--      چند بار و از کدام IPها حمله شد؟» اصلا قابلِ پرسیدن نیست.
--      ⚠️ ورودِ *موفق* از قبل در `sessions` هست (ip/user_agent/
--      origin/revoked_reason) — آن دوباره‌کاری نمی‌شود.
--
-- ── حریمِ خصوصی ──
-- ⚠️ شماره‌ی موبایلِ خام این‌جا نوشته **نمی‌شود**. برای تلاشِ ناموفق
-- روی شماره‌ای که اصلا حساب ندارد، شماره پوشانده ذخیره می‌شود
-- (`0912***۸۹`). دلیلش همان درسِ مهاجرتِ ۰۹۹ است: جدولِ OTP شماره‌ی
-- خام داشت و باید هرس می‌شد. `audit_logs` هرس نمی‌شود، پس هر PIIی
-- که این‌جا بنشیند برای همیشه می‌ماند.
-- برای تلاشِ ناموفق روی حسابِ *موجود* اصلا شماره لازم نیست:
-- `actor_id` خودِ کاربر است.
--
-- ⚠️ IP عمدا کامل ذخیره می‌شود — بدونِ آن این ژورنال برای بررسیِ
-- نفوذ بی‌فایده است، و همین حالا هم در `sessions` کامل هست.
--
-- ── اجرا ──
-- با `--single-transaction`. `CREATE INDEX` معمولی است نه
-- CONCURRENTLY: دومی داخلِ تراکنش اجرا نمی‌شود و آن‌وقت «توقف یعنی
-- هیچ‌چیز عوض نشد» را از دست می‌دهیم. جدول در این اندازه چند
-- میلی‌ثانیه قفل می‌شود.
-- ─────────────────────────────────────────────────────────────

-- ⚠️ `ALTER TABLE` قفلِ ACCESS EXCLUSIVE می‌گیرد و تا پایانِ کلِ
-- تراکنش (یعنی بعد از ساختِ هر چهار ایندکس) نگهش می‌دارد. اگر
-- تراکنشِ بلندی همان لحظه روی `audit_logs` باشد، این پشتِ آن صف
-- می‌بندد و هر خواننده و نویسنده پشتِ این. با این سقف، بدترین حالت
-- «مهاجرت لغو شد و هیچ‌چیز عوض نشد» است، نه سایتِ قفل‌شده.
SET lock_timeout = '3s';

-- ── ۱) عاملِ کاربر ──
ALTER TABLE public.audit_logs ADD COLUMN IF NOT EXISTS user_agent text;

-- ── ۲) ایندکس‌های صفحه‌ی ادمین ──
-- پرسشِ پیش‌فرض: «آخرین رویدادها»
CREATE INDEX IF NOT EXISTS audit_recent_idx
  ON public.audit_logs (created_at DESC);

-- «همه‌ی LOGIN_FAILها»، «همه‌ی تغییرهای کمیسیون»
CREATE INDEX IF NOT EXISTS audit_action_idx
  ON public.audit_logs (action, created_at DESC);

-- «هرچه این کاربر کرده» — ردیفِ بدونِ بازیگر (کرون) ایندکس نمی‌شود
CREATE INDEX IF NOT EXISTS audit_actor_idx
  ON public.audit_logs (actor_id, created_at DESC)
  WHERE actor_id IS NOT NULL;

-- «از این IP چه اتفاقی افتاد» — ستونِ تازه‌ی بررسیِ نفوذ
CREATE INDEX IF NOT EXISTS audit_ip_idx
  ON public.audit_logs (ip, created_at DESC)
  WHERE ip IS NOT NULL;

-- ── ۳) یادآوری ──
-- هیچ تابعِ تازه‌ای این‌جا ساخته نمی‌شود: صفحه‌ی ادمین از راهِ
-- PostgREST با کلیدِ service-role می‌خواند، همان الگوی بقیه‌ی پنل.
-- (پس تریگرِ رویدادیِ ۱۰۲ هم چیزی برای قفل‌کردن ندارد.)

NOTIFY pgrst, 'reload schema';
