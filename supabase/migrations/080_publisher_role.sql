-- ─────────────────────────────────────────────────────────────────
-- ۰۸۰ — نقشِ منتشرکننده روی آگهی
--
-- ── چرا Snapshot و نه خواندن از کاربر ──
-- کسی که هم فروشنده است هم مربی، آگهی را با یکی از این دو منتشر
-- می‌کند. اگر نشانِ آگهی از نقشِ *فعلیِ* کاربر خوانده شود، تغییرِ
-- بعدیِ نقش بی‌صدا نشانِ همه‌ی آگهی‌های قدیمی را عوض می‌کند — یعنی
-- آگهی‌ای که با نامِ «فروشنده» منتشر شده، فردا «مربی» می‌شود.
--
-- مثلِ مبلغِ ثبت‌نام و قیمتِ ارتقا: آنچه در لحظه‌ی انتشار درست بوده
-- همان‌جا ذخیره می‌شود.
-- ─────────────────────────────────────────────────────────────────

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS seller_role text;

/* ردیف‌های موجود نقشِ فعلیِ صاحبشان را می‌گیرند — یک‌بار، چون تا
   امروز چیزی ذخیره نشده بود و خالی‌گذاشتنشان یعنی آگهیِ بی‌نشان. */
UPDATE public.products p
   SET seller_role = u."primaryRole"
  FROM public.users u
 WHERE u.id = p."sellerId" AND p.seller_role IS NULL;

SELECT count(*) FILTER (WHERE seller_role IS NOT NULL) AS stamped,
       count(*) AS total
  FROM public.products;
