-- ۰۴۷ — سقفِ حجم روی باکتِ عمومی
--
-- ── چرا ──
-- باکتِ `club-media` هیچ `file_size_limit` نداشت. امروز خطری ندارد،
-- چون تنها راهِ نوشتن `service_role` است و مسیرِ `/api/upload` خودش
-- سقف می‌گذارد. ولی این یعنی تمامِ محافظت در یک لایه‌ی کد است: هر
-- مسیرِ سرورساید تازه‌ای که فراموش کند سقف بگذارد، می‌تواند فایلِ
-- بی‌اندازه بنویسد.
--
-- سقفِ باکت همان محافظت را یک لایه پایین‌تر می‌برد، جایی که فراموش‌شدنی
-- نیست. عدد از بزرگ‌ترین چیزی که امروز واقعاً می‌گذرد بالاتر گرفته شده
-- تا رفتارِ فعلی عوض نشود.
--
-- (باکتِ خصوصی از قبل سقفِ ۵۰ مگابایت دارد.)
-- ═══════════════════════════════════════════════════════════════

UPDATE storage.buckets
SET file_size_limit = 25 * 1024 * 1024      -- ۲۵ مگابایت
WHERE id = 'club-media' AND file_size_limit IS NULL;


-- ── گزارش ──
SELECT id,
       public,
       CASE WHEN file_size_limit IS NULL THEN 'ندارد'
            ELSE (file_size_limit / 1024 / 1024)::text || ' MB' END AS size_limit
FROM storage.buckets
ORDER BY id;
-- انتظار: club-media = 25 MB · bh-private = 50 MB
