-- کد پستی باشگاه
--
-- فیلد «کشور» از فرم برداشته شد: همه‌ی باشگاه‌ها ایران‌اند و آن فیلد
-- فقط یک ورودیِ آزاد بود که داده‌ی ناهمگون می‌ساخت (روی داده‌ی فعلی
-- هم «Iran» و هم «ایران» ثبت شده). ستونش عمداً حذف نمی‌شود — داده‌ی
-- موجود دست‌نخورده می‌ماند و فقط از UI برداشته می‌شود.
--
-- جایش کد پستی می‌آید، که برخلاف کشور یک چیز واقعاً مفید است: با
-- استعلامِ آن، آدرس و مختصات از سرویس ثبت‌شرکت‌ها می‌آید و دیگر لازم
-- نیست باشگاه‌دار آدرس را دستی و ناقص بنویسد.
--
-- ده رقم، بدون خط تیره. قید فقط شکل را می‌گیرد نه وجود را: باشگاه‌های
-- موجود کد پستی ندارند و نباید ثبتشان بشکند.
-- ─────────────────────────────────────────────────────────────

ALTER TABLE clubs ADD COLUMN IF NOT EXISTS "postalCode" text;

ALTER TABLE clubs DROP CONSTRAINT IF EXISTS clubs_postal_code_shape;
ALTER TABLE clubs ADD CONSTRAINT clubs_postal_code_shape
  CHECK ("postalCode" IS NULL OR "postalCode" ~ '^[0-9]{10}$');

COMMENT ON COLUMN clubs."postalCode" IS
  'کد پستی ده‌رقمی — مبنای استعلام آدرس. NULL یعنی هنوز وارد نشده.';
