-- ۰۶۵ — محتوای عمومیِ باشگاه که تا امروز فقط در مرورگرِ خودِ باشگاه‌دار بود
--
-- ── باگ ──
-- سه بخش از پنلِ باشگاه‌دار هیچ‌وقت به سرور نمی‌رفتند و مستقیم در
-- `localStorage` می‌نشستند:
--
--   • `club-coaches-<id>`  — فهرستِ مربیانِ باشگاه
--   • `club-stats-<id>`    — سال‌های فعالیت و ظرفیتِ روزانه
--   • `club-albums-<id>`   — آلبوم‌های گالری
--
-- و صفحه‌ی عمومیِ باشگاه (`app/clubs/[id]/page.tsx`) هم همان کلیدها را از
-- `localStorage`ِ **بازدیدکننده** می‌خواند. یعنی باشگاه‌دار همه‌چیز را
-- می‌دید و درست هم می‌دید، ولی هیچ بازدیدکننده‌ای هرگز چیزی نمی‌دید —
-- چون آن کلیدها فقط در مرورگرِ خودِ باشگاه‌دار وجود داشتند. تعویضِ
-- مرورگر یا پاک‌کردنِ کشِ خودِ باشگاه‌دار هم داده را برای همیشه می‌برد.
--
-- ── چرا jsonb روی همین جدول و نه جدولِ جدا ──
-- هر سه، محتوای نمایشیِ متعلق به یک باشگاه‌اند: هیچ‌وقت مستقل از باشگاه
-- جست‌وجو، فیلتر یا الحاق نمی‌شوند و همیشه با خودِ رکوردِ باشگاه خوانده
-- می‌شوند. `workingHours` هم دقیقاً به همین دلیل از اول jsonb بود.
--
-- ⚠️ آلبوم‌ها فقط **نشانیِ** فایل نگه می‌دارند، نه خودِ تصویر را. نسخه‌ی
-- مرورگری تصویرها را base64 ذخیره می‌کرد؛ همان چیز داخل این ستون یعنی
-- چند مگابایت در هر `select('*')` — و صفحه‌ی اولِ سایت همین را می‌زند.
-- کدِ آپلود به Storage منتقل شد.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.clubs
  ADD COLUMN IF NOT EXISTS coaches    jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS albums     jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS "clubStats" jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMIT;

-- ── بررسی ──
-- انتظار: سه ستون = ۳
SELECT count(*) AS content_columns
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'clubs'
  AND column_name IN ('coaches', 'albums', 'clubStats');
