-- ─────────────────────────────────────────────────────────────
-- ۱۰۵ — نگه‌داریِ `audit_logs`: فقط نوفه‌ی حمله، نه رویدادِ کسب‌وکار
--
-- ── مسئله ──
-- `audit_logs` از ۰۰۱ هست و هیچ هرسی ندارد. تا دیروز مهم نبود چون
-- هر ردیفش نتیجه‌ی یک کارِ واقعیِ انسانی بود (رزرو، پرداخت، تغییرِ
-- کمیسیون) و رشدش با حجمِ کسب‌وکار بسته می‌شد.
--
-- ⚠️ دو کنشِ تازه این را عوض کردند و هر دو **مهاجم‌ساخته‌اند**:
--   • `LOGIN_FAILED` (۱۰۴) — به ازای هر تلاشِ ناموفقِ ورود.
--   • `PAYMENT_AUTHORITY_MISMATCH` — از مسیرِ کال‌بکِ درگاه، که
--     احراز هویت ندارد و آن شاخه‌اش پیش از هر تغییرِ وضعیتی
--     برمی‌گردد، پس بی‌نهایت بار تکرارپذیر است.
-- یعنی این هرس، جمع‌کردنِ اثرِ همان دو تغییر است نه تمیزکاریِ عمومی.
--
-- ── چرا فهرستِ سفید، و نه «هرچه از X قدیمی‌تر» ──
-- ⚠️ بقیه‌ی ۱۲۵ کنش پاک **نمی‌شوند**، در هیچ سنی. ردیفِ مالی،
-- تغییرِ دسترسیِ ادمین و تاریخچه‌ی رزرو ارزششان با گذشتِ زمان کم
-- نمی‌شود — و یک هرسِ عمومی همان‌هایی را می‌برد که روزی لازم
-- می‌شوند. فهرست این‌جا سفید است نه سیاه: هر کنشِ تازه‌ای که اضافه
-- شود، پیش‌فرضش «هرگز پاک نشو» است.
--
-- `LOGIN_LOCKED` هم نگه داشته می‌شود: کم‌حجم است (یک ردیف در هر
-- دوره‌ی قفل، نه هر تلاش) و دقیقا همان چیزی است که می‌گوید حمله‌ای
-- در کار بوده.
--
-- ── چرا ۱۸۰ روز ──
-- شش ماه برای بررسیِ الگوی حمله بیش از کافی است. کمتر از ۳۰ روز
-- پذیرفته نمی‌شود تا یک اشتباهِ تایپی (`0`, `1`) کلِ ژورنالِ ورود را
-- نبرد.
--
-- ── اجرا ──
-- با `--single-transaction`. خودِ تابع چیزی را همین حالا پاک
-- نمی‌کند؛ فقط ساخته می‌شود. صدا زدنش با کرونِ `prune` است.
-- ─────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.bh_prune_audit(p_days integer DEFAULT 180)
RETURNS integer
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE n integer;
BEGIN
  -- ⚠️ کفِ ایمنی. بدونِ این، `bh_prune_audit(0)` — یک اشتباهِ تایپیِ
  -- ساده — کلِ تاریخچه‌ی تلاش‌های ورود را در یک لحظه می‌برد.
  IF p_days IS NULL OR p_days < 30 THEN
    RAISE EXCEPTION 'bh_prune_audit: p_days باید دستِ‌کم ۳۰ باشد (داده شد: %)', p_days;
  END IF;

  -- فهرستِ سفید. هر کنشِ دیگری — مالی، ادمین، رزرو — دست‌نخورده
  -- می‌ماند، در هر سنی.
  -- ⚠️ فقط کنشی این‌جا بیاید که *مهاجم* بتواند بسازد. رویدادی که
  -- نتیجه‌ی کارِ انسانِ واقعی است رشدش کرانه‌دار است و پاک‌کردنش فقط
  -- ضرر دارد.
  DELETE FROM public.audit_logs
   WHERE action IN ('LOGIN_FAILED', 'PAYMENT_AUTHORITY_MISMATCH')
     AND created_at < now() - make_interval(days => p_days);

  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END;
$$;

REVOKE ALL ON FUNCTION public.bh_prune_audit(integer) FROM PUBLIC, anon, authenticated;

NOTIFY pgrst, 'reload schema';
