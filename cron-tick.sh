#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
#  بیلیارد هاب — اجرای کرون‌های اپ روی سرورِ اختصاصی
#
#  ── چرا این فایل وجود دارد ──
#  چهار کرونِ اپ (`app/api/cron/*`) تنها زمان‌بندشان `apps/web/vercel.json`
#  بود. از روزی که سایت از ورسل به VPS مهاجرت کرد، آن فایل فقط یک
#  یادگار است و **هیچ‌کدام از این چهار مسیر دیگر اجرا نمی‌شوند**.
#
#  گران‌ترینش `complete-bookings` است: در مدلِ حسابِ مرکزی، باشگاه لحظه‌ی
#  *پرداخت* طلبکار نمی‌شود بلکه پس از *برگزاری* — و آن تبدیل فقط در
#  `bh_complete_due_bookings` اتفاق می‌افتد. بدونِ این اجرا هیچ رزروی
#  COMPLETED نمی‌شود، هیچ `CLUB_EARNING`ی در دفتر نوشته نمی‌شود، و تسویه
#  با باشگاه‌ها **غیرممکن** می‌ماند.
#
#  ── نصب ──
#     crontab -e
#     5 4 * * * /bin/bash /opt/billiardhub/cron-tick.sh >> /var/log/bh-cron.log 2>&1
#
#  با `/bin/bash` صدا زده می‌شود، نه مستقیم: فایل از ویندوز کامیت شده و
#  بیتِ اجرایی ندارد، پس اجرای مستقیم «permission denied» می‌دهد.
#
#  ── چرا ساعتِ ۴:۰۵ بامداد به وقتِ سرور ──
#  پشتیبان ۳ بامداد اجرا می‌شود؛ این‌جا فاصله می‌گیریم تا دو کارِ سنگین
#  روی هم نیفتند.
#
#  ── امنیت ──
#  اگر `CRON_SECRET` در `.env.local` باشد، همان به‌عنوان Bearer فرستاده
#  می‌شود. نبودنش هم مشکلی نیست: این اسکریپت مستقیم به
#  `127.0.0.1:3000` می‌زند و مسیرهای کرون درخواستِ لوکال را بدونِ راز
#  می‌پذیرند ولی درخواستِ آمده از nginx را نه (`lib/cron-guard.ts`).
# ═══════════════════════════════════════════════════════════════════════════
set -uo pipefail

APP_DIR="${BH_APP_DIR:-/opt/billiardhub}"
BASE="${BH_BASE_URL:-http://127.0.0.1:3000}"
ENV_FILE="$APP_DIR/apps/web/.env.local"

# فقط همین یک متغیر خوانده می‌شود؛ `source` کردنِ کلِ فایل یعنی هر رشته‌ی
# عجیبی در آن به شل برسد.
SECRET=""
if [ -r "$ENV_FILE" ]; then
  SECRET="$(sed -n 's/^CRON_SECRET=//p' "$ENV_FILE" | head -1 | tr -d '"'"'"'\r')"
  # ⚠️ اگر متغیر در فایل هست ولی استخراج نشد، **ساکت نمان**. از وقتی
  # گارد رازِ اشتباه را ۴۰۱ می‌کند، پارسِ ناموفق یعنی هیچ کرونی اجرا
  # نمی‌شود — همان فاجعه‌ای که این فایل برای رفعش نوشته شد.
  if grep -q '^CRON_SECRET=' "$ENV_FILE" && [ -z "$SECRET" ]; then
    echo "$(date '+%F %T') ✗ CRON_SECRET در $ENV_FILE هست ولی خوانده نشد — کرون اجرا نمی‌شود" >&2
    exit 1
  fi
fi

AUTH=()
[ -n "$SECRET" ] && AUTH=(-H "Authorization: Bearer $SECRET")

stamp() { date '+%Y-%m-%dT%H:%M:%S%z'; }

run() {
  local name="$1" out code body
  # ⚠️ `"${AUTH[@]+...}"`: زیرِ `set -u` در bashِ پیش از ۴٫۴، بسط دادنِ
  # یک آرایه‌ی خالی خودش «unbound variable» است و اسکریپت همان‌جا
  # می‌میرد — بی‌آنکه هیچ کرونی اجرا شده باشد.
  out="$(curl -sS --max-time 120 -w '\n%{http_code}' ${AUTH[@]+"${AUTH[@]}"} "$BASE/api/cron/$name" 2>&1)"
  code="$(printf '%s' "$out" | tail -1)"
  body="$(printf '%s' "$out" | sed '$d' | head -c 300)"
  if [ "$code" = "200" ]; then
    echo "$(stamp) ✓ $name $body"
  else
    # کدِ خروجِ ناصفر تا اگر روزی به آلارم وصل شد، دیده شود
    echo "$(stamp) ✗ $name HTTP $code $body" >&2
    FAILED=1
  fi
}

FAILED=0
# ترتیب مهم است: اول اسلاتِ رزروهای پرداخت‌نشده آزاد شود، بعد رزروهای
# برگزارشده تکمیل شوند (که سهمِ باشگاه را می‌سازد).
run expire-bookings
run complete-bookings
run expire-campaigns
run sweep-roles
# آخر از همه: پاک‌سازی. اگر شکست بخورد هیچ کارِ مالی‌ای معلق نمی‌ماند،
# و تا مهاجرت‌های ۰۹۸/۰۹۹ اجرا نشده‌اند خودش می‌گوید «مهاجرت اجرا نشده»
# بدونِ اینکه خطا بدهد.
run prune

exit "$FAILED"
