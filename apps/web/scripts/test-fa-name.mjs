/* تستِ واقعیِ جداکننده‌ی نام — نه گرپِ متنِ کد.
 *
 * گاردهای داخلِ test-tournaments فقط می‌گویند «قاعده صدا زده شده»؛
 * این‌جا خودِ خروجی سنجیده می‌شود. اجرا:
 *     node scripts/test-fa-name.mjs
 *
 * Node ۲۲ به بعد TypeScript را مستقیم می‌خواند، پس واردکردنِ فایلِ
 * .ts نیازی به بیلد ندارد.
 */
import { splitFaName } from '../lib/fa-name.ts'

const CASES = [
  /* [ورودی, نام, نام‌خانوادگی, چرا] */
  ['سید شهاب الدین ابوذریان', 'سید شهاب الدین', 'ابوذریان', 'پیشوندِ احترام + پسوندِ بسته'],
  ['علی لله گانی', 'علی', 'لله گانی', 'فامیلِ دوکلمه‌ای'],
  ['علی قره گوزلو', 'علی', 'قره گوزلو', 'فامیلِ دوکلمه‌ای'],
  /* از جدولِ واقعیِ رنکینگ — فامیلِ سه‌کلمه‌ای پوشش نداشت */
  ['امین فرید خسروی بروجنی', 'امین', 'فرید خسروی بروجنی', 'فامیلِ سه‌کلمه‌ای'],
  ['علی روشنی کیا', 'علی', 'روشنی کیا', 'فامیلِ دوکلمه‌ای — از جدولِ واقعی'],
  ['  میلاد کاشانی  ', 'میلاد', 'کاشانی', 'فاصله‌ی اضافه در دو سر'],
  ['سیاوش مزینی', 'سیاوش', 'مزینی', 'ساده'],
  ['حاج رضا محمدی', 'حاج رضا', 'محمدی', 'پیشوندِ احترام'],
  ['عبد الله رضایی', 'عبد الله', 'رضایی', 'پسوندِ بسته'],
  ['سید احمدی', 'سید', 'احمدی', 'دوکلمه‌ای — فامیل نباید خالی شود'],
  ['مهدی', 'مهدی', '', 'تک‌کلمه'],
  ['', '', '', 'خالی'],
  /* نویسه‌های عربی — از PDF فدراسیون یا کیبوردِ عربی */
  ['سيد شهاب الدين ابوذريان', 'سيد شهاب الدين', 'ابوذريان', 'ي و ك عربی'],
]

let pass = 0, fail = 0
for (const [input, wantFirst, wantLast, why] of CASES) {
  const got = splitFaName(input)
  const ok = got.firstName === wantFirst && got.lastName === wantLast
  ok ? pass++ : fail++
  console.log(`  ${ok ? '✓' : '✗'} «${input || '—'}» → «${got.firstName}» / «${got.lastName}»`
    + (ok ? `   (${why})` : `   ← انتظار «${wantFirst}» / «${wantLast}»`))
}
console.log(`\n${fail ? '❌' : '✅'}  ${pass} قبول · ${fail} رد`)
process.exit(fail ? 1 : 0)
