export const dynamic = 'force-dynamic'
import { NextResponse } from 'next/server'
import { loadFeatures } from '@/lib/features'

/* وضعیتِ Feature Flagها برای رابطِ کاربری.

   عمداً عمومی است: رابط باید حتی برای مهمان هم بداند چه چیزی را نشان
   ندهد. هیچ داده‌ی حساسی این‌جا نیست — فقط «این قابلیت روشن است یا نه»،
   همان چیزی که با نگاه‌کردن به صفحه هم معلوم می‌شود.

   نوشتن این‌جا ممکن نیست؛ فقط GET. تغییرِ مقدار منحصراً از
   `/api/admin/settings` انجام می‌شود که ادمین‌بودن را از نشست و
   دیتابیس تأیید می‌کند.

   ── چرا `no-store` ──────────────────────────────────────────────
   نسخه‌ی اولِ این هدر `s-maxage=30, stale-while-revalidate=300` بود.
   `stale-while-revalidate` صراحتاً به مرورگر اجازه می‌دهد تا ۳۰۰ ثانیه
   پاسخِ کهنه را بدونِ انتظار سرو کند — یعنی بعد از اینکه ادمین قابلیت
   را روشن می‌کرد، کاربر تا پنج دقیقه همچنان رابطِ خاموش می‌دید.

   برای پرچمی که *تنها* منبعِ تصمیمِ رابط است، هر درجه‌ای از کهنگی یعنی
   «روشن‌کردن کار نمی‌کند». هزینه‌ی `no-store` یک خواندنِ ایندکس‌شده به
   ازای هر بارگذاریِ صفحه است — نه پولینگ، نه سوکت، نه درخواستِ تکراری
   در ناوبریِ کلاینتی (Provider مقدار را در سطحِ ماژول نگه می‌دارد). */
export async function GET() {
  /* fresh: کشِ درون‌حافظه‌ای هم دور زده می‌شود. آن کش در هر تابعِ
     سرورلس نسخه‌ی جداگانه دارد، پس `invalidateFeatureCache()` در مسیرِ
     ادمین این مسیر را پاک نمی‌کند و همان کهنگیِ بالا از راهِ دیگری
     برمی‌گشت. */
  const features = await loadFeatures({ fresh: true })
  return NextResponse.json(features, {
    headers: { 'Cache-Control': 'no-store' },
  })
}
