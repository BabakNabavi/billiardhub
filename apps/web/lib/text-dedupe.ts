/* ─────────────────────────────────────────────────────────────
   حذفِ بازگویی در متنِ نوشته‌ی کاربر.

   ── مسئله ──
   پروفایل‌ها چند فیلدِ متنیِ آزاد دارند که کاربر اغلب تقریباً یک چیز
   در همه‌شان می‌نویسد. دادهٔ واقعیِ یک متخصص امروز:

       title = «خدمات فنی»
       intro = «خدمات فنی بیلیارد»
       about = [«کلیه خدمات فنی نصب و سرویس»]

   چاپِ هر سه پشتِ سرِ هم صفحه را حرّاف و بی‌اعتبار می‌کند.

   ── قاعده‌ای که *نباید* استفاده شود ──
   ⚠️ «یکی شاملِ دیگری ⟵ دومی را حذف کن» غلط است و یک‌بار همین‌جا
   داده خورد: با آن قاعده، چون «خدمات فنی بیلیارد» شاملِ «خدمات
   فنی» است، نسخه‌ی *بلندتر* حذف می‌شد و واژه‌ی «بیلیارد» برای همیشه
   از صفحه غایب می‌شد.

   ── قاعده‌ی درست ──
   وقتی دو متن بازگوییِ هم‌اند، **بلندتر می‌ماند**؛ حذف هرگز
   اطلاعات کم نمی‌کند. و «بازگویی» با نسبت سنجیده می‌شود نه با
   اختلافِ مطلق، وگرنه دو-سه واژه‌ی تازه همیشه قابلِ حذف‌اند.
   ───────────────────────────────────────────────────────────── */

/**
 * نیم‌فاصله، نشانه‌های جهت، و اعرابِ عربی در مقایسه نویسه حساب
 * نمی‌شوند.
 *
 * ⚠️ با کاراکترِ خام نوشته نمی‌شود: این‌ها در ویرایشگر نامرئی‌اند و
 * یک بازه‌ی اشتباه هفته‌ها کسی نمی‌فهمد. کدِ عددی، خودش سند است.
 *   200C نیم‌فاصله · 200E/200F نشانه‌های چپ‌به‌راست و راست‌به‌چپ
 *   064B–0652 اعراب
 */
/* eslint-disable-next-line no-misleading-character-class --
   قاعده هشدار می‌دهد که جداکردنِ نشانه‌های ترکیبی از حرفِ پایه
   می‌تواند ناخواسته باشد. این‌جا دقیقاً همان کارِ خواسته‌شده است:
   اعراب باید برداشته شود تا «مُتخصص» و «متخصص» یکی شمرده شوند. */
const STRIP = /[\u200C\u200E\u200F\u064B-\u0652]/gu

export const norm = (s: unknown) => String(s ?? '').replace(/\s+/g, ' ').trim()

const bare = (s: string) => s.replace(STRIP, '')

/**
 * آیا دو متن عملاً یک حرف می‌زنند؟
 *
 * شرط: یکی در دیگری باشد **و** کوتاه‌تر دستِ‌کم نیمی از بلندتر باشد.
 * زیرِ آن نسبت، متنِ بلندتر حرفِ تازه‌ی جدی دارد و ادغام یعنی
 * پنهان‌کردنِ محتوا.
 */
export function echoes(a: string, b: string): boolean {
  const x = bare(a), y = bare(b)
  if (!x || !y) return false
  if (!x.includes(y) && !y.includes(x)) return false
  const [short, long] = x.length <= y.length ? [x, y] : [y, x]
  /* ⚠️ آستانه سخاوتمند است و اشکالی ندارد: چون همیشه *بلندتر*
     می‌ماند، ادغامِ زیادی بدترین حالتش این است که یک خط به‌جای دو
     خطِ تقریباً یکسان چاپ شود. هیچ واژه‌ای از دست نمی‌رود.
     ۰٫۶ برای دادهٔ واقعی («خدمات فنی» ۹ در «خدمات فنی بیلیارد»
     ۱۷ ⟵ ۰٫۵۳) تنگ بود و هر دو چاپ می‌شدند. */
  return short.length / long.length >= 0.5
}

/**
 * روی *جایگاه* کار می‌کند: خروجی هم‌طولِ ورودی است و هر عضو یا
 * متنِ نگه‌داشته‌شده است یا `null`.
 *
 * ⚠️ چرا این شکل لازم شد: نسخه‌ی اولِ این ماژول فقط آرایه‌ی فشرده
 * برمی‌گرداند، و صداکننده مجبور بود دو بار جدا صدایش بزند — یک‌بار
 * برای عنوان/معرفی و یک‌بار برای «درباره» — و بعد دومی را با اولی
 * فیلتر کند. همان فیلترِ مرزی دوباره *کوتاه‌تر* را ترجیح می‌داد:
 * با `title=«خدمات فنی»` و `about=[«خدمات فنی بیلیارد و اسنوکر»]`
 * کلِ بندِ درباره حذف می‌شد و «و اسنوکر» برای همیشه می‌رفت.
 *
 * با یک گذرِ واحد روی همه‌ی متن‌ها، «بلندتر می‌ماند» در *مرزها* هم
 * برقرار است، و جایگاه هم معلوم می‌ماند تا صداکننده بداند هر متنِ
 * بازمانده کجای صفحه بنشیند.
 */
export function keepLongest(values: readonly string[]): (string | null)[] {
  const out: (string | null)[] = values.map(norm).map(v => (v ? v : null))
  for (let i = 0; i < out.length; i++) {
    const a = out[i]
    if (!a) continue
    for (let j = 0; j < i; j++) {
      const b = out[j]
      if (!b || !echoes(a, b)) continue
      /* بلندتر می‌ماند و در *زودترین* جایگاهِ گروه می‌نشیند، تا جای
         متن در صفحه بالا و پایین نپرد. */
      out[j] = bare(a).length > bare(b).length ? a : b
      out[i] = null
      break
    }
  }
  return out
}

/**
 * همان `keepLongest`، فشرده — برای جایی که جایگاه اهمیتی ندارد.
 */
export const dropEchoes = (values: readonly string[]): string[] =>
  keepLongest(values).filter((x): x is string => !!x)
