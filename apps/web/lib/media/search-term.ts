/* ─────────────────────────────────────────────────────────────
   ساختِ عبارتِ جست‌وجو برای PostgREST — منبعِ واحد.

   دو مصرف‌کننده دارد و باید یکی بمانند: پیشنهادهای نوارِ جست‌وجو
   (`/api/media/suggest`) و خودِ نتایج (`listPublic`).

   ⚠️ اگر این دو از هم بیفتند، بدترین حالتِ ممکن ساخته می‌شود:
   کاربر پیشنهادی را می‌بیند، رویش کلیک می‌کند، و به صفحه‌ی «چیزی
   پیدا نشد» می‌رسد — یعنی محصول به او دروغ گفته است.
   ───────────────────────────────────────────────────────────── */

/* ⚠️ `*` و `_` هم باید پاک شوند، نه فقط `%`:
     · PostgREST خودش `*` را در مقدارِ `ilike` به `%` ترجمه می‌کند
     · `_` در LIKE یعنی «یک نویسه‌ی دلخواه»
   بدونِ این دو، یک درخواستِ ناشناسِ `?q=*` تبدیل می‌شد به
   `ilike '%%%'` روی سه ستون به‌علاوه‌ی مرتب‌سازی روی کلِ جدول. */
const UNSAFE = /[%_*,()\\]/g

/** ورودیِ خام کاربر → عبارتی که بی‌خطر داخل الگوی `ilike` می‌نشیند. */
export function sanitizeIlike(raw: unknown, max = 60): string {
  if (typeof raw !== 'string') return ''
  return raw.slice(0, max).replace(UNSAFE, ' ').trim()
}

/* ⚠️ این تا با `normalizeFa` فرق دارد و باید هم داشته باشد:
   `normalizeFa` نویسه حذف می‌کند (فاصله، اعراب، نویسه‌های نامرئی)
   و برای همین برای برجسته‌کردنِ بخشِ تایپ‌شده به‌درد نمی‌خورد —
   جای برش‌ها را جابه‌جا می‌کند. این یکی طولِ رشته را نگه می‌دارد.

   ⚠️ عمدا `toLowerCase` **نمی‌کند**: کوچک‌کردن در یونیکد طول‌ثابت
   نیست («İ» یعنی U+0130 به دو نویسه باز می‌شود). هرجا کوچک‌کردن
   لازم است، `foldCase` پایین را صدا بزن؛ برای الگوی `ilike` اصلا
   لازم نیست چون خودش به بزرگی و کوچکی حساس نیست. */
export const foldFa = (s: string): string =>
  s.replace(/[يى]/g, 'ی').replace(/ك/g, 'ک')

/**
 * تای فارسی + کوچک‌کردن، برای *مقایسه* (نه برای برش‌زدن).
 *
 * ⚠️ اگر جایی می‌خواهی با نتیجه‌ی این تابع روی رشته‌ی اصلی `slice`
 * بزنی، اول طول‌ها را بسنج — همان تله‌ی «İ».
 */
export const foldCase = (s: string): string => foldFa(s).toLowerCase()

/** همان تا، در جهتِ عکس — برای ردیف‌هایی که با صفحه‌کلید عربی ذخیره شده‌اند. */
const toArabic = (s: string): string =>
  s.replace(/[یى]/g, 'ي').replace(/ک/g, 'ك')

/** دو صورتِ متعارفِ یک عبارت: همه‌فارسی و همه‌عربی. */
export function faVariants(term: string): string[] {
  const fa = foldFa(term)
  return [...new Set([fa, toArabic(fa)])]
}

/**
 * الگوی `or=` برای PostgREST روی چند ستون.
 *
 * ⚠️ `ilike` در پستگرس «ی/ي» و «ک/ك» را یکی نمی‌بیند، پس کسی که با
 * صفحه‌کلید عربی «كلوپ» می‌نویسد بدونِ این هیچ نتیجه‌ای نمی‌گیرد.
 *
 * ⚠️ پوششش کامل **نیست** و عمدا هم نیست: فقط دو صورتِ یکدستِ
 * همه‌فارسی و همه‌عربی ساخته می‌شود. عنوانی که مخلوط ذخیره شده
 * («كیف» با کافِ عربی و یایِ فارسی) با هیچ‌کدام نمی‌خورد. حلِ کاملش
 * یک ستونِ تولیدیِ نرمال‌شده به‌علاوه‌ی ایندکسِ trgm است، یعنی تغییرِ
 * اسکیما، و آن با تاییدِ صریحِ مالک انجام می‌شود نه این‌جا.
 */
export function faIlikeOr(cols: readonly string[], term: string): string {
  return faVariants(term)
    .flatMap(f => cols.map(c => `${c}.ilike.%${f}%`))
    .join(',')
}

/**
 * شرطِ «این برچسب را دارد» برای یک ستونِ آرایه‌ای.
 *
 * ⚠️ لازم است چون نوارِ پیشنهاد برچسب هم پیشنهاد می‌دهد، ولی
 * `listPublic` فقط عنوان و توضیح را می‌گشت — یعنی کاربر روی
 * برچسبِ پیشنهادشده کلیک می‌کرد و به «چیزی پیدا نشد» می‌رسید.
 *
 * ⚠️ `cs` تطبیقِ **دقیق** عضو است، نه جست‌وجوی جزئی: برای همین
 * فقط مسیرِ «کلیک روی پیشنهاد» را درست می‌کند، که همان جایی است
 * که عبارت عینا برابرِ برچسب است.
 */
export function faTagContains(col: string, term: string): string {
  return faVariants(term).map(f => `${col}.cs.{"${f}"}`).join(',')
}
