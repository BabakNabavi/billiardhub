import type { NextRequest } from 'next/server'

/* ─────────────────────────────────────────────────────────────
   نگهبانِ مسیرهای کرون.

   ── مسئله ──
   `/api/cron/complete-bookings` وضعیتِ مالی را عوض می‌کند: رزرو را
   COMPLETED می‌کند و سهمِ باشگاه و کمیسیون را در دفتر می‌نویسد.
   نسخه‌ی قبلی اگر `CRON_SECRET` تنظیم نبود، **کاملا باز** بود — یعنی
   هر کسی از اینترنت می‌توانست اجرایش کند.

   ── چرا فقط «راز اجباری» جواب نمی‌دهد ──
   راز روی سرور در `.env.local` است و ما از این‌جا نه می‌خوانیمش نه
   می‌نویسیمش. اگر مسیر را بدونِ راز ۵۰۳ کنیم و راز تنظیم نباشد، کرون
   بی‌صدا هیچ‌کاری نمی‌کند — یعنی دقیقا همان فاجعه‌ای که داشتیم.

   ── راه‌حل ──
   دو در، نه یکی:
     • راز درست ⇒ مجاز (از هر جا)
     • درخواستِ واقعا لوکال ⇒ مجاز
   `cron-tick.sh` مستقیم به `127.0.0.1:3000` می‌زند و از nginx رد
   نمی‌شود، پس هدرِ `x-forwarded-for` ندارد. هر درخواستی که از بیرون
   بیاید nginx آن هدر را می‌گذارد و این‌جا رد می‌شود.
   ───────────────────────────────────────────────────────────── */

const LOCAL = new Set(['127.0.0.1', '::1', '::ffff:127.0.0.1', 'localhost'])

export function cronForbidden(req: NextRequest): { message: string; status: number } | null {
  /* ⚠️ وقتی راز تنظیم **است**، همان تنها ملاک است. نسخه‌ی اول در
     صورتِ رازِ اشتباه به بررسیِ لوکال می‌افتاد — یعنی راز دقیقا در
     تنها حالتی که تنظیم شده بود تزئینی می‌شد. */
  const secret = process.env.CRON_SECRET
  if (secret) {
    const auth = req.headers.get('authorization') || ''
    return auth === `Bearer ${secret}` ? null : { message: 'دسترسی مجاز نیست', status: 401 }
  }

  /* ⚠️ `x-forwarded-for` را **نمی‌شود** به‌عنوان اثبات پذیرفت (کاربر
     جعلش می‌کند)؛ فقط به‌عنوان نشانه‌ی «از پروکسی آمده» استفاده
     می‌شود. نبودنش یعنی درخواست مستقیم به پورتِ اپ خورده، و آن پورت
     روی VPS فقط از خودِ ماشین در دسترس است. */
  if (req.headers.get('x-forwarded-for')) {
    return { message: 'دسترسی مجاز نیست', status: 401 }
  }

  const host = (req.headers.get('host') || '').split(':')[0]
  if (host && !LOCAL.has(host)) {
    return { message: 'دسترسی مجاز نیست', status: 401 }
  }

  return null
}
