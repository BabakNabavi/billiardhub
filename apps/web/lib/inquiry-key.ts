/* ─────────────────────────────────────────────────────────────
   کلیدِ سرویس‌های استعلام (s.api.ir).

   ── چرا این فایل هست ──
   `SMS_API_KEY` از روزِ اول دو کار می‌کرد: هم پیامک می‌فرستاد هم
   شش سرویسِ استعلام را تغذیه می‌کرد — کد ورود، شاهکار، استعلام
   بانکی، جواز کسب، کد پستی و اعتبارسنجیِ ایمیل. اسمش فقط از یکی از
   آن‌ها می‌گفت.

   وقتی پیامک به ملی‌پیامک منتقل شد و مقدارِ همان متغیر عوض شد، هر
   شش سرویس با هم افتادند — **از جمله کد ورود، یعنی کسی نمی‌توانست
   وارد شود یا ثبت‌نام کند.** و چون پیامک درست کار می‌کرد، هیچ‌چیز
   نمی‌گفت مشکل از کلید است.

   حالا هر سرویس کلیدِ خودش را دارد:
     SAPIR_API_KEY (یا SMS_API_KEY قدیمی) → s.api.ir
     MELIPAYAMAK_KEY                      → ملی‌پیامک
   ───────────────────────────────────────────────────────────── */

/** کلیدِ ملی‌پیامک GUID سی‌ودو رقمیِ شانزده‌شانزدهی است */
const looksLikeMelipayamak = (k: string) => /^[0-9a-fA-F]{32}$/.test(k.replace(/-/g, ''))

/**
 * کلیدِ سرویس‌های استعلام — تهی اگر تنظیم نشده یا اشتباه باشد.
 *
 * اگر کلیدِ ملی‌پیامک در این متغیر بنشیند، عمداً تهی برمی‌گردد. آن
 * کلید این‌جا کار نمی‌کند و پذیرفتنش یعنی هر استعلام با «سرویس در
 * دسترس نیست» برمی‌گردد بدونِ اینکه علت پیدا باشد — همان چیزی که
 * یک‌بار اتفاق افتاد. «پیکربندی نشده» پیامِ درست‌تری است.
 */
export function inquiryKey(): string {
  const k = (process.env.SAPIR_API_KEY || process.env.SMS_API_KEY || '').trim()
  if (!k) return ''
  if (looksLikeMelipayamak(k)) {
    console.error(
      '[inquiry] کلیدِ ملی‌پیامک در SMS_API_KEY نشسته است. ' +
      'سرویس‌های استعلام (کد ورود، شاهکار، بانک، جواز، کد پستی) کار نمی‌کنند. ' +
      'کلیدِ s.api.ir را در SAPIR_API_KEY بگذارید.')
    return ''
  }
  return k
}

/** برای صفحه‌ی سلامت — بدونِ نشان‌دادنِ خودِ کلید */
export function inquiryKeyState(): { set: boolean; wrongKey: boolean } {
  const raw = (process.env.SAPIR_API_KEY || process.env.SMS_API_KEY || '').trim()
  return { set: !!inquiryKey(), wrongKey: !!raw && looksLikeMelipayamak(raw) }
}
