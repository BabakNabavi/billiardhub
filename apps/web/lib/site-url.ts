/* نشانیِ سایت — یک منبعِ واحد.

   تا امروز دامنه در چند جای کد هاردکد بود و دو تایشان اصلاً غلط
   بودند: صفحه‌ی خبر و ویدیو لینکِ اشتراک‌گذاری را روی
   `mybilliardhb1.vercel.app` می‌ساختند — دامنه‌ای که دیگر دامنه‌ی این
   پروژه نیست. یعنی هر کس خبری را در واتساپ یا تلگرام می‌فرستاد، لینکِ
   شکسته می‌فرستاد.

   ترتیبِ اولویت:
   ۱) `NEXT_PUBLIC_SITE_URL` — اگر روزی لازم شد دامنه عوض شود
   ۲) دامنه‌ی رسمی، نوشته‌شده در خودِ کد

   ── چرا `VERCEL_PROJECT_PRODUCTION_URL` برداشته شد ──
   این متغیر را خودِ Vercel می‌گذارد و مقدارش از تنظیماتِ دامنه‌ی پروژه
   می‌آید. یک‌بار هنگامِ ورزکردن با تنظیماتِ دامنه، `www` چند دقیقه
   دامنه‌ی اصلی شد؛ همان مقدار در بیلد جا افتاد و از آن پس سایت به گوگل
   می‌گفت آدرسِ رسمی‌اش `www.billiardhub.net` است — در حالی که محتوا
   روی دامنه‌ی بدونِ www سرو می‌شد. یعنی یک تغییرِ گذرا در پنلِ Vercel
   می‌توانست بی‌صدا آدرسِ رسمیِ سایت را جابه‌جا کند.

   حالا دامنه در کد است: با هر بیلد یکسان می‌ماند، در Git دیده می‌شود،
   و عوض‌کردنش نیازمندِ یک کامیتِ آگاهانه است نه یک کلیک.

   دامنه‌ی رسمی بدونِ www است و www به آن ۳۰۷ می‌خورد؛ این دو باید
   همیشه هم‌جهت بمانند، وگرنه گوگل دو نسخه از هر صفحه می‌بیند. */
export const SITE_URL = (
  process.env.NEXT_PUBLIC_SITE_URL
  || 'https://billiardhub.net'
).replace(/\/+$/, '')

/** نشانیِ کاملِ یک مسیر — برای canonical و اشتراک‌گذاری.
 *
 *  در مرورگر عمداً از `window.location.origin` استفاده می‌شود: هر
 *  دامنه‌ای که کاربر واقعاً روی آن است، همان درست است. این کاری
 *  می‌کند که لینکِ اشتراک‌گذاری حتی روی دامنه‌ی پیش‌نمایش هم درست
 *  بماند و با عوض‌شدنِ دامنه هیچ‌جای کد لازم نباشد دست بخورد. */
export function absoluteUrl(path: string): string {
  const p = path.startsWith('/') ? path : `/${path}`
  if (typeof window !== 'undefined') return window.location.origin + p
  return SITE_URL + p
}

/* ── مبدأِ عمومی برای نشانیِ بازگشتِ درگاه ──────────────────────────
   ── باگی که این رفع می‌کند ──
   هفت مسیرِ پرداخت `req.nextUrl.origin` را می‌ساختند. روی Vercel درست
   بود چون خودش هدرها را بازنویسی می‌کرد. ولی پشتِ nginx، Next فقط
   نشانیِ داخلی را می‌بیند — یعنی `http://localhost:3000`.

   نتیجه‌اش این بود: کاربر پول را می‌داد، درگاه او را به `localhost`
   برمی‌گرداند، مرورگر «ERR_CONNECTION_REFUSED» می‌داد و **رزرو
   هیچ‌وقت قطعی نمی‌شد** — در حالی که پول کم شده بود.

   ── چرا هدرِ درخواست را باور نمی‌کنیم ──
   `X-Forwarded-Host` را هر کسی می‌تواند جعل کند، و نشانیِ بازگشتِ
   درگاه جایی نیست که به ورودیِ کاربر اعتماد شود: مهاجم می‌توانست
   کاربر را پس از پرداخت به دامنه‌ی خودش بفرستد.

   پس همیشه از `SITE_URL` — که در env یا در کد است و دستِ کاربر
   نیست. */
export function callbackOrigin(): string {
  return SITE_URL
}
