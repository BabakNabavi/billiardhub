const CLOSED: ReadonlySet<string> = new Set(['/players'])

export const isClosedSection = (href: string): boolean => CLOSED.has(href)

/* ظاهرِ دکمه‌ی بسته: سرِ جایش می‌ماند ولی کم‌رنگ و بی‌واکنش */
export const CLOSED_STYLE = { opacity: 0.4, pointerEvents: 'none', cursor: 'default' } as const

/* ویژگی‌های دسترس‌پذیرِ لینکِ بسته — صفحه‌خوان «غیرفعال» می‌خواند، Tab از رویش رد می‌شود */
export const closedLinkProps = {
  'aria-disabled': true,
  tabIndex: -1,
} as const

/* کلیکِ لینکِ بسته جایی نمی‌رود (pointer-events هم بسته است؛ این لایه‌ی دوم است) */
