/* ─────────────────────────────────────────────────────────────
   دلیلِ رد شدن — فهرستِ بسته، مشترکِ نقش و باشگاه.

   ── چرا بسته ──
   این متن داخلِ پیامک می‌رود و سرویسِ پیامک می‌خواهد بداند یک متغیر
   چه مقدارهایی می‌تواند بگیرد. متنِ آزادِ ادمین یعنی مقدارِ نامعلوم
   در پیامکی که از طرفِ سایت می‌رود.

   جدا از آن، فهرستِ بسته خودش بهتر است: دلیل‌ها یکدست می‌مانند، و
   ادمینی که عجله دارد نمی‌تواند چیزی بنویسد که کاربر نفهمد یا
   بی‌ادبانه به نظر برسد.

   یادداشتِ آزادِ ادمین حذف نشده — در داشبورد و ممیزی می‌ماند، فقط
   داخلِ پیامک نمی‌رود.
   ───────────────────────────────────────────────────────────── */

export interface RejectReason { code: string; label: string }

/* ⚠️ هر تغییری در `label`ها باید از طریق تیکت به سرویسِ پیامک هم
   اعلام شود، وگرنه ارسال با مقدارِ اعلام‌نشده رد می‌شود. */
export const REJECT_REASONS: RejectReason[] = [
  { code: 'doc_unreadable',  label: 'ناخوانا بودن مدرک' },
  { code: 'doc_expired',     label: 'منقضی بودن مدرک' },
  { code: 'doc_mismatch',    label: 'مغایرت مدرک با مشخصات' },
  { code: 'doc_missing',     label: 'ارائه نشدن مدرک معتبر' },
  { code: 'info_incomplete', label: 'ناقص بودن اطلاعات' },
  { code: 'info_wrong',      label: 'نادرست بودن اطلاعات' },
  { code: 'photo_unsuitable', label: 'نامناسب بودن تصاویر' },
  { code: 'duplicate',       label: 'تکراری بودن ثبت' },
  { code: 'other',           label: 'موارد دیگر' },
]

const BY_CODE = new Map(REJECT_REASONS.map(r => [r.code, r.label]))
const LABELS = new Set(REJECT_REASONS.map(r => r.label))

/**
 * برچسبِ امن برای پیامک — همیشه یکی از مقدارهای اعلام‌شده.
 *
 * ورودیِ ناشناخته به «موارد دیگر» می‌افتد، نه این‌که خودش برود. این
 * عمدی است: تنها راهِ تضمینِ این‌که هرگز مقدارِ اعلام‌نشده‌ای به سرویس
 * نرود، همین است — حتی اگر روزی یک مسیرِ قدیمی متنِ آزاد بفرستد.
 */
export function rejectLabel(input: unknown): string {
  const s = String(input ?? '').trim()
  if (BY_CODE.has(s)) return BY_CODE.get(s)!
  /* خودِ برچسب هم پذیرفته است — بعضی مسیرها متن می‌فرستند نه کد */
  if (LABELS.has(s)) return s
  return 'موارد دیگر'
}
