/* لیگاتورِ «الله» در نام‌های فارسی.
 *
 * فونت دنباله‌ی ل+ل+ه را به لیگاتورِ «الله» تبدیل می‌کند و یک تشدید
 * رویش می‌کشد. نامِ خانوادگیِ «لله گانی» هیچ تشدیدی در داده ندارد
 * (رشته‌ی ذخیره‌شده U+0651 ندارد) ولی روی صفحه با تشدید دیده می‌شود.
 *
 * ⚠️ چرا با `font-feature-settings` حل نشد:
 * خاموش‌کردنِ liga/clig/dlig در وزنی که سایت استفاده می‌کند اثری
 * نداشت — لیگاتور از `rlig` می‌آید. و `rlig` لیگاتورِ *لازم* است:
 * خاموش‌کردنش «لا» را در نام‌هایی مثل غلامرضا و جلالی به خطر می‌اندازد.
 *
 * ZWJ (U+200D) بینِ دو لام لیگاتور را می‌شکند ولی پیوندِ حروف را نگه
 * می‌دارد، و چون فقط روی همین دنباله گذاشته می‌شود هیچ حرفِ دیگری را
 * لمس نمی‌کند. در مرورگر با فونتِ واقعیِ سایت سنجیده شد.
 */

/* با fromCharCode نوشته می‌شود نه با خودِ نویسه: ZWJ نامرئی است و
   در کد به چشم نمی‌آید — کسی که فایل را می‌خواند فکر می‌کند رشته
   خالی است، و هر ابزارِ فرمت‌کننده‌ای هم می‌تواند بی‌صدا حذفش کند. */
const ZWJ = String.fromCharCode(0x200D)

/** «لله» را طوری می‌نویسد که فونت لیگاتورِ الله نسازد. */
export const breakAllahLigature = (s: string): string =>
  s ? s.replace(/لله/g, `ل${ZWJ}له`) : s
