/* ─────────────────────────────────────────────────────────────
   لینک واتساپ و تماس — روی نرمال‌سازیِ موجود.

   ── چرا این فایل ──
   لینک واتساپ مستقیم از مقدارِ خامِ فیلد ساخته می‌شد:
   `https://wa.me/${tech.whatsapp}`. هر چیزی که کاربر تایپ یا پیست
   کرده بود عینا داخل نشانی می‌رفت — «@»، فاصله، خط تیره، «+»، و
   حتی نشانی کاملِ wa.me. نتیجه‌اش لینکِ شکسته بود و کاربر
   نمی‌توانست به متخصص پیام بدهد.

   ⚠️ نرمال‌سازی از نو نوشته **نشد**: `lib/auth/phone.ts` از قبل
   `normalizePhone` را دارد (ارقام فارسی/عربی، `+۹۸`، `۰۰۹۸`،
   بدونِ صفر، جداکننده‌ها) و تستِ خودش را هم دارد. این‌جا فقط شکلِ
   موردنیازِ wa.me از همان ساخته می‌شود.

   ⚠️ پاک‌سازی باید **هنگام ساختِ لینک** انجام شود نه فقط هنگام
   ذخیره: ردیف‌هایی که از قبل با مقدارِ کثیف ذخیره شده‌اند همچنان
   در دیتابیس‌اند و اعتبارسنجیِ فرم به آن‌ها نمی‌رسد.
   ───────────────────────────────────────────────────────────── */

import { normalizePhone, toLatinDigits } from './auth/phone'

/**
 * شماره به شکلی که wa.me می‌خواهد: بین‌المللی، بدون «+» و بدون صفر.
 * اگر شماره معتبر نبود `''` — و آن‌وقت دکمه اصلا ساخته نمی‌شود.
 */
export function waNumber(raw: unknown): string {
  const local = normalizePhone(raw)   // `09xxxxxxxxx` یا `''`
  return local ? '98' + local.slice(1) : ''
}

/**
 * شماره برای `tel:` — موبایل به شکل محلیِ `09xxxxxxxxx`، و هر
 * شماره‌ی ثابتِ معتبر همان‌طور که هست (فقط پاک‌سازی‌شده).
 *
 * ⚠️ عمدا **سخت‌گیرتر از `waNumber` نیست**: نسخه‌ی اول این تابع
 * مستقیم `normalizePhone` بود که هرچه `09XXXXXXXXX` نباشد را رد
 * می‌کند. یعنی متخصصی که تلفنِ کارگاه ثبت کرده بود (`02112345678`)
 * دکمه‌ی تماسش کلا ناپدید می‌شد — پس‌رفتی نسبت به رفتار قبلی.
 * واتساپ باید سخت‌گیر بماند (شماره باید موبایل باشد)، ولی زنگ‌زدن
 * به خط ثابت کاملا معتبر است.
 */
export function telNumber(raw: unknown): string {
  const mobile = normalizePhone(raw)
  if (mobile) return mobile
  if (typeof raw !== 'string') return ''
  /* ارقام فارسی/عربی هم پذیرفته می‌شوند؛ «+» ابتدایی می‌ماند چون
     برای شماره‌ی بین‌المللی معنا دارد. */
  const s = toLatinDigits(raw).trim()
  const plus = s.startsWith('+')
  const d = s.replace(/\D/g, '')
  /* کوتاه‌تر از هشت رقم شماره‌ی تلفن نیست — «۱۲۳» یا سالِ ثبت */
  return d.length >= 8 && d.length <= 15 ? (plus ? '+' : '') + d : ''
}

/** نشانی گفت‌وگوی واتساپ، یا `''` اگر شماره معتبر نبود. */
export function waLink(raw: unknown, text?: string): string {
  const n = waNumber(raw)
  if (!n) return ''
  const t = (text ?? '').trim()
  return `https://wa.me/${n}${t ? `?text=${encodeURIComponent(t)}` : ''}`
}
