/* رنگ‌بندی رتبه‌ها — به سبک جدول رنکینگ فدراسیون جهانی:
   ۱ مشکی، ۲–۸ صورتی، ۹–۱۶ آبی، ۱۷–۳۲ قهوه‌ای، ۳۳–۶۴ سبز (دسته یک)، بقیه خاکستری.
   یک منبع برای صفحه‌ی رنکینگ، جدولِ کلیِ تصویری و نتیجه‌ی جست‌وجو. */
export const rankColor = (r: number): string =>
  r === 1 ? '#111111'
  : r <= 8 ? '#F06EAE'
  : r <= 16 ? '#3D63E6'
  : r <= 32 ? '#A9613F'
  : r <= 64 ? '#229A47'
  : '#6F6A5C'
