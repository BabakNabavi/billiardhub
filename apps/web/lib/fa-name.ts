/* جداکردنِ نام از نام‌خانوادگیِ فارسی، وقتی فقط یک رشته داریم.
 *
 * ⚠️ چرا حدسِ ساده جواب نمی‌دهد:
 *   «علی لله گانی»            → نام یک کلمه، فامیل دو کلمه
 *   «سید شهاب الدین ابوذریان» → نام سه کلمه، فامیل یک کلمه
 * هر قاعده‌ی «کلمه‌ی اول = نام» یا «کلمه‌ی آخر = فامیل» یکی از این دو
 * را خراب می‌کند.
 *
 * قاعده‌ی این‌جا از ساختِ خودِ نامِ فارسی می‌آید، نه از شمارشِ کلمه:
 *   · پیشوندهای احترام (سید، میر، حاج، …) به *نام* می‌چسبند
 *   · پسوندهای بسته (الدین، الله، …) به کلمه‌ی پیش از خود می‌چسبند
 * بقیه‌ی رشته نام‌خانوادگی است.
 *
 * این فقط یک حدسِ اولیه است. هرجا ادمین نام و فامیل را صریح وارد
 * کرده باشد، آن مقدم است و این تابع اصلاً صدا زده نمی‌شود.
 */

/* ⚠️ نامِ کپی‌شده از PDF فدراسیون یا کیبوردِ عربی «ي» و «ك» عربی
   دارد، نه «ی» و «ک» فارسی — و «سيد» با «سید» برابر نیست. کلید پیش
   از جست‌وجو یکسان‌سازی می‌شود؛ خروجی همان نویسه‌های اصلی است. */
/* ⚠️ بازه اعراب با کد نوشته می‌شود نه با خود نویسه. اگر با خود
   نویسه نوشته شود، دو نویسه نامرئی داخل رجکس می‌نشیند و هر پاک‌سازی
   متنی می‌تواند حذفشان کند — آن‌وقت رجکس بی‌صدا به /[-]/ تبدیل
   می‌شود و به‌جای اعراب، خط تیره را پاک می‌کند. */
const DIACRITICS = /[ً-ْ]/g

const norm = (t: string) =>
  t.replace(/[يى]/g, 'ی').replace(/ك/g, 'ک').replace(DIACRITICS, '')

/** پیشوندهایی که بخشی از نامِ کوچک‌اند، نه فامیل */
const HONORIFICS = new Set(['سید', 'میر', 'حاج', 'حاجی', 'شیخ', 'آقا', 'سیده'])

/** پسوندهایی که به کلمه‌ی قبلِ خود می‌چسبند و نام را ادامه می‌دهند */
const BOUND = new Set(['الدین', 'اله', 'الله', 'العابدین', 'الاسلام', 'الملک'])

export interface SplitName { firstName: string; lastName: string }

export function splitFaName(full: string): SplitName {
  const parts = String(full ?? '').trim().split(/\s+/).filter(Boolean)
  if (parts.length === 0) return { firstName: '', lastName: '' }
  if (parts.length === 1) return { firstName: parts[0]!, lastName: '' }

  /* ⚠️ دو قید که نباید «ساده» شوند:
     · length > 2 — وگرنه «سید احمدی» فامیلِ خالی می‌گیرد
     · i < length - 1 — تضمین می‌کند یک کلمه برای فامیل بماند */
  let i = 1                                   // دستِ‌کم یک کلمه نام است
  if (HONORIFICS.has(norm(parts[0]!)) && parts.length > 2) i = 2
  while (i < parts.length - 1 && BOUND.has(norm(parts[i]!))) i++

  return {
    firstName: parts.slice(0, i).join(' '),
    lastName: parts.slice(i).join(' '),
  }
}
