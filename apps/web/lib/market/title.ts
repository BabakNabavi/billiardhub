/* ═══════════════════════════════════════════════════════════════
   عنوانِ محصول در بازار — دو تکه، یک منبع.
   ───────────────────────────────────────────────────────────────
   کارتِ آگهی و صفحه‌ی محصول فقط `title` را نشان می‌دادند، و `title`
   موقعِ ثبت از «دسته‌بندی + نوع» ساخته می‌شود. یعنی خریدار روی کارت
   «چوب اسنوکر» می‌دید و همین. کدام چوب؟ برند و مدل — که فروشنده هر
   دو را نوشته بود — تا داخلِ «مشخصات فنی» پایینِ صفحه‌ی محصول دیده
   نمی‌شدند.

   حالا عنوان دو تکه است:

     head → «چوب اسنوکر»    (دسته‌بندی و نوع — درشت)
     tail → «O'min classic» (برند و مدل — ریزتر، کنارش)

   ── چرا head همان `title` است و از دسته/نوع بازسازی نمی‌شود ──
   فروشنده می‌تواند عنوان را در صفحه‌ی ویرایش دست ببرد. اگر نمایش
   عنوان را از روی دسته و نوع از نو می‌ساخت، آن ویرایش بی‌صدا نادیده
   می‌شد — فروشنده عنوانش را عوض می‌کرد و کارت همان چیزِ قبلی را
   نشان می‌داد.

   ── و چرا برند/مدل جداگانه می‌آیند، نه داخلِ `title` ──
   آگهی‌های ثبت‌شده‌ی امروز برند و مدل را در `title` ندارند. اگر قرار
   بود از راهِ عنوان بیاید، همه‌ی آگهی‌های موجود باید مهاجرت می‌کردند
   و آگهیِ ویرایش‌شده هم باید عنوانش بازنویسی می‌شد. ستون‌های
   `brand`/`model` سرِ جایشان هستند؛ همان‌جا خوانده می‌شوند.
   ═══════════════════════════════════════════════════════════════ */

const clean = (v: unknown) => String(v ?? '').trim().replace(/\s+/g, ' ')

/* فرمِ ثبت برای گزینه‌ی «سایر» توضیحِ کاربر را با پیشوند ذخیره می‌کند
   («سایر: کیوبال»). آن پیشوند برای خریدار معنایی ندارد. */
const plain = (v: unknown) => clean(v).replace(/^سایر\s*[:：]\s*/, '')

const has = (hay: string, needle: string) =>
  !!needle && hay.toLowerCase().includes(needle.toLowerCase())

export interface ProductTitleFields {
  /** نگاشتِ نمایشی */
  name?: unknown
  /** ردیفِ خامِ جدولِ products */
  title?: unknown
  brand?: unknown
  model?: unknown
}

export interface ProductTitleParts {
  /** دسته‌بندی و نوع — با فونتِ درشت‌تر */
  head: string
  /** برند و مدل، اگر فروشنده نوشته باشد و در head تکرار نشده باشد */
  tail: string
}

/** عنوان را به دو تکه‌ی نمایشی می‌شکند. */
/* ── نام‌های قدیمیِ «نوع» در دسته‌ی توپ ──
   فهرستِ فرم عوض شد («۲۲ تایی اسنوکر» ⇒ «توپ اسنوکر»)، ولی آگهی‌های
   ثبت‌شده هنوز رشته‌ی قدیمی را در `title` دارند. مهاجرتِ دیتابیس برای
   یک برچسبِ نمایشی بیش‌ازحد است و عنوانی را هم که فروشنده دستی
   ویرایش کرده خراب می‌کند؛ پس نگاشت هنگامِ نمایش انجام می‌شود.

   فقط عبارتِ دقیق جایگزین می‌شود، نه هر تطبیقِ جزئی — وگرنه عنوانی
   مثل «ست ۲۲ تایی اسنوکر دست‌دوم» بی‌دلیل دست‌کاری می‌شد. */
const LEGACY_TYPE: Record<string, string> = {
  /* ── چرا بدونِ واژه‌ی «توپ» ──
     عنوان موقعِ ثبت از «دسته‌بندی + نوع» ساخته می‌شود، پس رشته‌ی
     ذخیره‌شده از قبل نامِ دسته را دارد: «توپ ۱۵ تایی پاکت بیلیارد».
     نسخه‌ی اولِ این نگاشت به «توپ پاکت بیلیارد» تبدیل می‌کرد و
     نتیجه‌اش «توپ توپ پاکت بیلیارد» می‌شد. نگاشت باید فقط *نوع* را
     بدهد؛ دسته سرِ جایش هست. */
  '۲۲ تایی اسنوکر': 'اسنوکر',
  '۱۵ تایی پاکت بیلیارد': 'پاکت بیلیارد',
  '۳ تایی کارامبول': 'کارامبول',
}

/** «توپ توپ پاکت» ⇒ «توپ پاکت» — واژه‌ی تکراریِ چسبیده حذف می‌شود */
function dedupeWords(s: string): string {
  const w = s.split(' ')
  const out: string[] = []
  for (const x of w) if (out[out.length - 1] !== x) out.push(x)
  return out.join(' ')
}

export function modernizeType(s: string): string {
  let out = s
  for (const [old, neo] of Object.entries(LEGACY_TYPE)) {
    if (out === old) { out = neo; break }
    if (out.startsWith(`${old} `)) { out = `${neo}${out.slice(old.length)}`; break }
    if (out.endsWith(` ${old}`)) { out = `${out.slice(0, -old.length)}${neo}`; break }
  }
  /* تورِ ایمنی: هر تکرارِ چسبیده — از هر منشأیی — جمع می‌شود. */
  return dedupeWords(out)
}

export function productTitleParts(p: ProductTitleFields): ProductTitleParts {
  const head = modernizeType(plain(p.name) || plain(p.title) || 'محصول')

  /* ترتیب همان ترتیبِ فرم است: برند، بعد مدل. */
  const raw = [plain(p.brand), plain(p.model)]
    .filter(Boolean)
    /* چیزی که از قبل در عنوان هست دوباره گفته نمی‌شود — عنوانی که
       فروشنده خودش نوشته ممکن است برند را داشته باشد. */
    .filter(x => !has(head, x))

  /* «O'min» و «O'min classic» با هم یعنی «O'min O'min classic».
     تکه‌ای که داخلِ تکه‌ی بلندتر تکرار شده حذف می‌شود. */
  const kept = raw.filter((x, i) => !raw.some((y, j) => j !== i && y.length > x.length && has(y, x)))

  return { head, tail: kept.join(' ') }
}

/** عنوانِ کاملِ یک‌خطی — برای alt تصویر، متنِ واتساپ، جستجو و گزارشِ تخلف. */
export function productTitle(p: ProductTitleFields): string {
  const { head, tail } = productTitleParts(p)
  return [head, tail].filter(Boolean).join(' ')
}
