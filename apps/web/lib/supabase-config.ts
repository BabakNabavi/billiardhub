/* ─────────────────────────────────────────────────────────────
   نشانیِ Supabase خودمیزبان — منبعِ واحد. **فقط سمتِ سرور.**

   ── چرا ──
   این نشانی در سه فایل جدا هاردکد شده بود (`supabase-server`,
   `social-server`, `otp-server`) در حالی که `lib/media/storage.ts`
   آن را از متغیرِ محیطی می‌خواند.

   دو مسئله داشت:
   ۱) اگر روزی مقدارِ محیطی و مقدارِ هاردکد با هم فرق می‌کردند، دو
      بخشِ کد دو نشانیِ متفاوت می‌ساختند — و آن نوع اختلاف بی‌صداست:
      فایل آپلود می‌شود ولی از نشانیِ دیگری خوانده.
   ۲) جابه‌جاییِ پروژه (یا مهاجرتِ آینده‌ی Storage) یعنی پیداکردنِ
      همه‌ی جاهایی که این رشته تایپ شده.

   ── چرا دیگر تکیه‌گاه ندارد ──
   این‌جا یک `FALLBACK` به نشانیِ یک پروژه‌ی **ابریِ** Supabase بود که
   دیگر استفاده نمی‌شود. اگر متغیرِ محیطی جا می‌افتاد، اپ بی‌صدا سراغِ
   آن می‌رفت: آپلود به نشانیِ درست می‌رفت و خواندن از نشانیِ دیگر، یا
   همه‌ی تصویرها بی‌صدا بلاک می‌شدند — چون CSP فقط دامنه‌ی خودمان را
   مجاز می‌داند.

   روی یک پروژه‌ی زنده، شکستِ بی‌صدا از کرش بدتر است: کرش همان لحظه
   دیده می‌شود، ولی نشانیِ غلط ممکن است هفته‌ها بماند و تازه وقتی
   کشف شود که داده‌ای گم شده باشد.

   ── چرا «خالی» کافی نبود ──
   نسخه‌ی اولِ این گارد فقط نبودنِ متغیر را می‌گرفت. ولی همان نشانیِ
   مرده هنوز در `.env.production` نشسته بود، یعنی مقدار **خالی
   نبود** و گارد هرگز شلیک نمی‌کرد — دقیقاً همان حالتی که قرار بود
   از بین برود. پس شرط این است: یا خالی، یا میزبانی که مالِ ما
   نیست.

   ── چرا این فایل به مرورگر نمی‌رود ──
   `thumbUrl` که تنها چیزِ موردِ نیازِ کامپوننت‌های کلاینت بود به
   `lib/media/thumb.ts` منتقل شد. اگر این ماژول دوباره از یک
   کامپوننتِ `'use client'` وارد شود، این خطا داخلِ باندلِ مرورگر
   می‌نشیند و یک بیلدِ بدونِ متغیر، به‌جای خطای سرور، صفحه‌ی سفید
   به بازدیدکننده می‌دهد. تستِ «فقط سمتِ سرور» در
   `scripts/test-tournaments.mjs` همین را نگه می‌دارد.
   ───────────────────────────────────────────────────────────── */

import { SUPABASE_URL_RAW as RAW } from './supabase-url'

/** میزبانی که مالِ ما نیست — پروژه‌ی ابریِ Supabase دیگر استفاده نمی‌شود */
const isCloudHost = (u: string): boolean => {
  try { return new URL(u).hostname.endsWith('.supabase.co') } catch { return false }
}

if (!RAW || isCloudHost(RAW)) {
  throw new Error(
    RAW
      ? `NEXT_PUBLIC_SUPABASE_URL روی «${RAW}» تنظیم شده که پروژه‌ی ابریِ Supabase است. ` +
        'این پروژه از Supabase خودمیزبان استفاده می‌کند؛ نشانیِ درست را ' +
        '(مثلاً https://billiardhub.net) در apps/web/.env.local بگذارید.'
      : 'NEXT_PUBLIC_SUPABASE_URL تنظیم نشده است. ' +
        'نشانیِ Supabase خودمیزبان (مثلاً https://billiardhub.net) را در apps/web/.env.local بگذارید. ' +
        'بدونِ آن هیچ تصویر، ویدیو یا فایلی بارگذاری نمی‌شود.',
  )
}

export const SUPABASE_URL: string = RAW

/** باکتِ عمومی — عکس و ویدیوی قابلِ نمایش. */
export const PUBLIC_BUCKET = 'club-media'

/** باکتِ خصوصی — دایرکت، اعلان، مدارک. لینکِ عمومی ندارد. */
export const PRIVATE_BUCKET = 'bh-private'

/** ریشه‌ی نشانیِ عمومیِ یک باکت. */
export const publicRoot = (bucket = PUBLIC_BUCKET) =>
  `${SUPABASE_URL}/storage/v1/object/public/${bucket}/`

