/* ─────────────────────────────────────────────────────────────
   نشانیِ پروژه‌ی Supabase — منبعِ واحد.

   ── چرا ──
   این نشانی در سه فایل جدا هاردکد شده بود (`supabase-server`,
   `social-server`, `otp-server`) در حالی که `lib/media/storage.ts`
   آن را از متغیرِ محیطی می‌خواند.

   دو مسئله داشت:
   ۱) اگر روزی مقدارِ محیطی و مقدارِ هاردکد با هم فرق می‌کردند، دو
      بخشِ کد دو نشانیِ متفاوت می‌ساختند — و آن نوع اختلاف بی‌صداست:
      فایل آپلود می‌شود ولی از نشانیِ دیگری خوانده.
   ۲) جابه‌جاییِ پروژه (یا مهاجرتِ آینده‌ی Storage) یعنی پیداکردنِ
      همه‌ی جاهایی که این رشته تایپ شده.

   مقدارِ ثابت به‌عنوان تکیه‌گاه می‌ماند: اگر متغیرِ محیطی نبود، رفتار
   دقیقاً همان امروز است و چیزی نمی‌شکند.
   ───────────────────────────────────────────────────────────── */

const FALLBACK = 'https://bxnomfjjvhdtbnqvgjmh.supabase.co'

export const SUPABASE_URL: string =
  (process.env.NEXT_PUBLIC_SUPABASE_URL ?? '').trim().replace(/\/+$/, '') || FALLBACK

/** باکتِ عمومی — عکس و ویدیوی قابلِ نمایش. */
export const PUBLIC_BUCKET = 'club-media'

/** باکتِ خصوصی — دایرکت، اعلان، مدارک. لینکِ عمومی ندارد. */
export const PRIVATE_BUCKET = 'bh-private'

/** ریشه‌ی نشانیِ عمومیِ یک باکت. */
export const publicRoot = (bucket = PUBLIC_BUCKET) =>
  `${SUPABASE_URL}/storage/v1/object/public/${bucket}/`

/* ═══════════════════════════════════════════════════════════════
   بندانگشتی — تصویرِ آپلودشده در اندازه‌ی واقعیِ نمایش.
   ───────────────────────────────────────────────────────────────
   ── چه چیزی اندازه‌گیری شد ──
   صفحه‌ی اصلیِ Production، عکسِ یک باشگاه:

       نشانیِ خام (object/public)   ۲٬۳۳۲ کیلوبایت PNG
       همان با render/image w=640   ۳۶ کیلوبایت WebP

   ۶۵ برابر، برای کادری که روی صفحه ۳۲۰ پیکسل عرض دارد. و همان
   تصویر **شش بار** در HTML رندر می‌شد — یعنی حدودِ ۱۴ مگابایت
   تصویر برای یک صفحه، روی اتصالی که HTTP/1.1 است و بیش از شش
   جریانِ هم‌زمان نمی‌دهد. بقیه‌ی دارایی‌ها پشتِ همین صف می‌ماندند و
   نتیجه‌اش همان «سکته»ی هیرو و دیرآمدنِ تصویرها بود.

   ── چرا این راه، نه `next/image` ──
   این تصویرها روی دامنه‌ی خودمان سرو می‌شوند و Supabaseِ خودمیزبان
   `imgproxy` را از قبل بالا دارد. یعنی تبدیل بدونِ افزودنِ لایه‌ی
   بهینه‌سازیِ Next انجام می‌شود و باری روی سرورِ Node نمی‌گذارد.
   قالب هم خودکار است: مرورگری که WebP بپذیرد، WebP می‌گیرد.

   ── قاعده ──
   عرض را از روی اندازه‌ی واقعیِ کادر بده، نه دلبخواه. برای صفحه‌های
   با چگالیِ دو برابر، دو برابرِ عرضِ CSS منطقی است.
   ═══════════════════════════════════════════════════════════════ */

const OBJECT_SEG = '/storage/v1/object/public/'
const RENDER_SEG = '/storage/v1/render/image/public/'

/**
 * نشانیِ بندانگشتیِ یک تصویرِ Storage.
 * هر چیزِ دیگری (مسیرِ محلیِ `/images/…`، data URI، نشانیِ بیگانه)
 * دست‌نخورده برمی‌گردد — این تابع هیچ‌وقت نشانی را خراب نمی‌کند.
 */
export function thumbUrl(
  src: string | null | undefined,
  width: number,
  quality = 72,
): string {
  const s = String(src ?? '')
  if (!s || !s.includes(OBJECT_SEG)) return s
  /* نشانی‌ای که از قبل پارامتر دارد دوباره پارامتر نمی‌گیرد */
  const [base] = s.split('?')
  return `${base!.replace(OBJECT_SEG, RENDER_SEG)}?width=${Math.round(width)}&quality=${quality}`
}
