/* ─────────────────────────────────────────────────────────────
   نشانیِ خامِ Supabase — تنها جایی که این متغیرِ محیطی خوانده می‌شود.

   ── چرا جدا از `supabase-config` ──
   `supabase-config` نبودنِ نشانی را خطای صریح می‌داند، و همان خطا
   نباید به باندلِ مرورگر برسد (وگرنه یک بیلدِ بدونِ متغیر به‌جای
   خطای سرور، صفحه‌ی سفید به بازدیدکننده می‌دهد).

   ولی چند ماژولِ سمتِ کلاینت هم به همین نشانی نیاز دارند. پیش‌تر
   هرکدام مستقیم `process.env` را می‌خواندند — پنج خواننده‌ی جدا با
   پنج رفتارِ متفاوت در نبودِ مقدار: یکی `!` می‌زد، یکی `?? ''`،
   یکی `null` برمی‌گرداند.

   این فایل فقط مقدار را می‌دهد و هیچ قضاوتی نمی‌کند، پس هم سرور
   می‌تواند واردش کند هم کلاینت. اعتبارسنجی جای خودش در
   `supabase-config` است.

   ── چرا مقدار در بیلد جا می‌افتد ──
   `NEXT_PUBLIC_*` هنگام بیلد به‌صورت متن جایگزین می‌شود، پس این
   خواندن در زمانِ اجرا هزینه‌ای ندارد و در کلاینت هم همان مقدارِ
   لحظه‌ی بیلد است.
   ───────────────────────────────────────────────────────────── */

