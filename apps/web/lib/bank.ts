/* ── شبا (IBAN) ─────────────────────────────────────────────── */

/** IR + ۲۴ رقم */
export function formatIban(v: string): string {
  const d = digitsOnly(String(v).replace(/^IR/i, '')).slice(0, 24)
  return d ? `IR${d}` : ''
}

/** اعتبارسنجیِ شبا با mod-97 (استانداردِ ISO 13616) */
export function isValidIban(v: string): boolean {
  const raw = String(v || '').replace(/\s/g, '').toUpperCase()
  const m = /^IR(\d{24})$/.exec(raw)
  if (!m) return false
  /* چهار نویسه‌ی اول به انتها می‌رود و حروف به عدد تبدیل می‌شوند: I=18، R=27 */
  const rearranged = raw.slice(4) + '1827' + raw.slice(2, 4)
  let rem = 0
  for (const ch of rearranged) rem = (rem * 10 + Number(ch)) % 97
  return rem === 1
}

/** نمایشِ خوانا: IR12 3456 7890 … */
export function prettyIban(v: string): string {
  const raw = formatIban(v)
  return raw ? raw.replace(/(.{4})/g, '$1 ').trim() : ''
}

