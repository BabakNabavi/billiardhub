/* ─────────────────────────────────────────────────────────────
   اثرانگشتِ خطا — کلیدِ تجمیع.

   ── چرا این‌جا و نه داخلِ route ──
   `instrumentation.ts` هم به این تابع نیاز دارد، و آن فایل در هر دو
   رانتایمِ Node و Edge بارگذاری می‌شود. نسخه‌ی اول از داخلِ همان
   route ایمپورتش می‌کرد و آن فایل `node:crypto` داشت — که در Edge
   وجود ندارد و بیلد را می‌شکست. یک ماژولِ بی‌وابستگی، مشکل را از
   ریشه حذف می‌کند.

   ── چرا FNV-1a و نه SHA ──
   این هش هیچ نقشِ امنیتی ندارد؛ فقط باید «همان خطا» را به همان
   کلید برساند. برخوردِ تصادفی یعنی دو باگ در یک ردیف جمع شوند —
   ناخوشایند ولی بی‌خطر. در عوض خالص است و همه‌جا کار می‌کند.
   ───────────────────────────────────────────────────────────── */

function fnv1a(s: string): string {
  let h = 0x811c9dc5
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    /* ضربِ ۱۶۷۷۷۶۱۹ با جمعِ شیفت‌ها، تا از دقتِ ۳۲بیتی بیرون نزند */
    h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0
  }
  return h.toString(16).padStart(8, '0')
}

/**
 * مسیرِ صفحه بدونِ کوئری‌استرینگ و هش.
 *
 * ⚠️ کوئری‌استرینگ هرگز ذخیره نمی‌شود. پرتکرارترین مسیرهایی که خطا
 * می‌دهند، کالبکِ درگاه‌هاست و نشانی‌شان شناسه‌ی پرداخت و توکنِ
 * بازگشت را حمل می‌کند؛ ریختنشان در ژورنالی که ادمین می‌خواند،
 * نشتِ داده است.
 */
export function pathOf(url?: string): string {
  try { return new URL(url ?? '', 'https://x.invalid').pathname } catch { return '' }
}

/**
 * منبع + پیام + اولین قابِ پشته + مسیرِ صفحه.
 *
 * ⚠️ عددها از کلید برداشته می‌شوند: «۴۰۴ برای id=931» و «id=77» یک
 * باگ‌اند. بدونِ این، هر رخداد اثرانگشتِ تازه می‌ساخت و تجمیع بی‌اثر
 * می‌شد — یعنی دقیقا همان سیلِ ردیفی که این طراحی برای جلوگیری از
 * آن است.
 */
export function fingerprintOf(source: string, message: string, stack?: string, url?: string): string {
  const frame = (stack ?? '').split('\n').find(l => /\bat\b|@/.test(l))?.trim() ?? ''
  /* ⚠️ عددها فقط از مسیر و قابِ پشته برداشته می‌شوند، نه از پیام:
     «HTTP 401» و «HTTP 403» دو باگ‌اند و نباید در یک ردیف جمع شوند. */
  const path = pathOf(url).replace(/\d+/g, '#')
  /* ⚠️ `source` جزءِ کلید است: خطای سرور و خطای مرورگر با پیامِ
     یکسان یک چیز نیستند، و بدونِ آن ردیفِ اول فیلدهای ردیفِ دوم را
     برای همیشه قفل می‌کرد. */
  const key = [source, message, frame.replace(/\d+/g, '#'), path].join('|').slice(0, 600)
  /* دو هش با دو نمکِ متفاوت، کنار هم: فضای کلید را از ۳۲ به ۶۴ بیت
     می‌برد و برخورد را عملا از بین. */
  return fnv1a(key) + fnv1a('salt:' + key)
}
