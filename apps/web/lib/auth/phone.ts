/* ─────────────────────────────────────────────────────────────
   نرمال‌سازیِ شماره‌ی موبایل — یک تعریفِ واحد برای کلِ پروژه.

   تا امروز هر مسیر شکلِ خودش را داشت:
     • ورود        `.eq('phone', phone)` با ورودیِ خام
     • ثبت‌نام     همان
     • فراموشی رمز `/^09\d{9}$/` روی ورودیِ خام
     • OTP         فقط غیرِ رقم را حذف می‌کرد

   آن `replace(/[^0-9]/g,'')` یک تلهٔ خاموش داشت: ارقامِ فارسی
   (`۰۹۱۲…`) در بازه‌ی [0-9] نیستند، پس **کاملاً حذف** می‌شدند و
   شماره به رشته‌ی خالی تبدیل می‌شد. کاربری که با کیبوردِ فارسی تایپ
   می‌کرد، بی‌هیچ پیامِ روشنی رد می‌شد.

   این‌جا همه‌ی شکل‌های رایج به یک قالبِ واحد می‌رسند:
     ۰۹۱۲۳۴۵۶۷۸۹ / +989123456789 / 989123456789 / 9123456789
     ⇒ 09123456789
   ───────────────────────────────────────────────────────────── */

const FA = '۰۱۲۳۴۵۶۷۸۹'
const AR = '٠١٢٣٤٥٦٧٨٩'

/** ارقامِ فارسی و عربی را به لاتین تبدیل می‌کند */
export function toLatinDigits(v: string): string {
  return String(v ?? '')
    .replace(/[۰-۹]/g, ch => String(FA.indexOf(ch)))
    .replace(/[٠-٩]/g, ch => String(AR.indexOf(ch)))
}

/**
 * شماره را به قالبِ استانداردِ `09XXXXXXXXX` می‌آورد.
 * اگر شماره‌ی معتبرِ ایرانی نباشد، رشته‌ی خالی برمی‌گرداند.
 */
export function normalizePhone(input: unknown): string {
  let d = toLatinDigits(String(input ?? '')).replace(/\D/g, '')
  if (!d) return ''

  /* پیش‌شماره‌ی کشور به هر شکلی که آمده باشد */
  if (d.startsWith('0098')) d = d.slice(4)
  else if (d.startsWith('98')) d = d.slice(2)

  /* بدونِ صفرِ ابتدایی (۹۱۲…) */
  if (d.length === 10 && d.startsWith('9')) d = '0' + d

  return /^09\d{9}$/.test(d) ? d : ''
}

/** آیا ورودی یک موبایلِ معتبرِ ایرانی است؟ */
export const isValidPhone = (input: unknown): boolean => normalizePhone(input) !== ''

/* ── پیشوندهای واقعیِ اپراتورها ────────────────────────────────
   `^09\d{9}$` فقط *شکل* را می‌سنجد، نه *وجود* را. شماره‌ای مثل
   `0900…` این الگو را پاس می‌کند ولی هیچ اپراتوری آن را نداده و هیچ
   سیم‌کارتی با آن وجود ندارد.

   چرا این مهم است: سرویسِ پیامک چنین شماره‌ای را می‌پذیرد و
   `success: true` برمی‌گرداند، ولی پیامک به جایی نمی‌رسد. نتیجه‌اش
   دقیقاً همان چیزی است که در این پروژه دیده شد — کاربر «کد ارسال شد»
   می‌بیند و تا ابد منتظرِ کدی می‌ماند که هرگز فرستاده نشده. هیچ خطایی
   هم در هیچ لاگی نمی‌نشیند، چون از نظرِ سرویس همه‌چیز موفق بوده.

   بازه‌های تخصیص‌یافته (سازمان تنظیم مقررات):
     ۰۹۰۱–۰۹۰۵            ایرانسل
     ۰۹۱۰–۰۹۱۹            همراه اول
     ۰۹۲۰–۰۹۲۲            رایتل
     ۰۹۳۰–۰۹۳۹            ایرانسل / تالیا / کوثر
     ۰۹۴۱                 ایرانسل TD-LTE
     ۰۹۹۰–۰۹۹۹            همراه اول، آرین‌تل، شاتل، سامانتل، آپتل

   عمداً کمی سخاوتمند است (کلِ ۰۹۹x و ۰۹۳x) تا تخصیصِ تازه‌ی یک اپراتور
   کاربرِ واقعی را پشتِ در نگذارد. آنچه قطعاً بسته می‌شود همان‌هایی است
   که هیچ‌وقت تخصیص نیافته‌اند: ۰۹۰۰، ۰۹۰۶–۰۹۰۹، ۰۹۲۳–۰۹۲۹، ۰۹۴۰،
   ۰۹۴۲–۰۹۸۹. */
const ASSIGNED_PREFIX = /^09(0[1-5]|1\d|2[0-2]|3\d|41|9\d)\d{7}$/

/**
 * شماره‌ای که هم شکلش درست است و هم پیشوندش واقعاً به اپراتوری تعلق دارد.
 * خروجی مثلِ `normalizePhone` است؛ در غیرِ این صورت رشته‌ی خالی.
 */
export function normalizeMobile(input: unknown): string {
  const p = normalizePhone(input)
  return p && ASSIGNED_PREFIX.test(p) ? p : ''
}

/** آیا این پیشوند به اپراتورِ واقعی تعلق دارد؟ (روی شماره‌ی نرمال‌شده) */
export const hasAssignedPrefix = (phone: string): boolean => ASSIGNED_PREFIX.test(phone)

/** پیامِ واحد برای شماره‌ای که پیشوندش وجودِ خارجی ندارد */
export const INVALID_MOBILE_MESSAGE =
  'این شماره‌ی موبایل معتبر نیست. لطفاً شماره را با پیش‌شماره‌ی درستِ اپراتور وارد کنید.'
