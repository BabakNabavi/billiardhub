/* ─────────────────────────────────────────────────────────────
   نرمال‌سازیِ شماره‌ی موبایل — یک تعریفِ واحد برای کلِ پروژه.

   تا امروز هر مسیر شکلِ خودش را داشت:
     • ورود        `.eq('phone', phone)` با ورودیِ خام
     • ثبت‌نام     همان
     • فراموشی رمز `/^09\d{9}$/` روی ورودیِ خام
     • OTP         فقط غیرِ رقم را حذف می‌کرد

   آن `replace(/[^0-9]/g,'')` یک تلهٔ خاموش داشت: ارقامِ فارسی
   (`۰۹۱۲…`) در بازه‌ی [0-9] نیستند، پس **کاملاً حذف** می‌شدند و
   شماره به رشته‌ی خالی تبدیل می‌شد. کاربری که با کیبوردِ فارسی تایپ
   می‌کرد، بی‌هیچ پیامِ روشنی رد می‌شد.

   این‌جا همه‌ی شکل‌های رایج به یک قالبِ واحد می‌رسند:
     ۰۹۱۲۳۴۵۶۷۸۹ / +989123456789 / 989123456789 / 9123456789
     ⇒ 09123456789
   ───────────────────────────────────────────────────────────── */

const FA = '۰۱۲۳۴۵۶۷۸۹'
const AR = '٠١٢٣٤٥٦٧٨٩'

/** ارقامِ فارسی و عربی را به لاتین تبدیل می‌کند */
export function toLatinDigits(v: string): string {
  return String(v ?? '')
    .replace(/[۰-۹]/g, ch => String(FA.indexOf(ch)))
    .replace(/[٠-٩]/g, ch => String(AR.indexOf(ch)))
}

/**
 * شماره را به قالبِ استانداردِ `09XXXXXXXXX` می‌آورد.
 * اگر شماره‌ی معتبرِ ایرانی نباشد، رشته‌ی خالی برمی‌گرداند.
 */
export function normalizePhone(input: unknown): string {
  let d = toLatinDigits(String(input ?? '')).replace(/\D/g, '')
  if (!d) return ''

  /* پیش‌شماره‌ی کشور به هر شکلی که آمده باشد */
  if (d.startsWith('0098')) d = d.slice(4)
  else if (d.startsWith('98')) d = d.slice(2)

  /* بدونِ صفرِ ابتدایی (۹۱۲…) */
  if (d.length === 10 && d.startsWith('9')) d = '0' + d

  return /^09\d{9}$/.test(d) ? d : ''
}

/** آیا ورودی یک موبایلِ معتبرِ ایرانی است؟ */
export const isValidPhone = (input: unknown): boolean => normalizePhone(input) !== ''
