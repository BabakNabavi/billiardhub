/* ─────────────────────────────────────────────────────────────
   متن‌های آماده‌ی پیامکِ باشگاه به اعضا.

   ── چرا متنِ آزاد نیست ──
   خطِ خدماتیِ ملی‌پیامک متنِ دلخواه نمی‌پذیرد؛ هر متن باید یک‌بار در
   پنلِ آن‌ها ثبت و تأیید شود. ولی حتی اگر می‌شد هم، این‌جا متنِ آزاد
   نمی‌گذاشتیم: باشگاه‌دار به شماره‌ی موبایلِ اعضا دسترسی پیدا می‌کند و
   متنِ بی‌قید یعنی پلتفرم مسئولِ هرچیزی است که فرستاده می‌شود.

   پس مقدارها هم عمداً تنگ‌اند — تاریخ، عنوان، درصد — نه پاراگرافِ آزاد.
   یک آرگومانِ بی‌قید همان متنِ آزاد است با یک گامِ بیشتر.

   `{0}` همیشه نامِ گیرنده است و خودِ سامانه پرش می‌کند؛ باشگاه‌دار
   فقط `{1}` به بعد را می‌بیند.
   ───────────────────────────────────────────────────────────── */

export interface ClubTemplateField {
  /** نمایهٔ آرگومان در متن — ۱ به بعد (۰ نامِ گیرنده است) */
  index: number
  label: string
  placeholder: string
  /* هیچ فیلدی متنِ آزاد نیست.
     سرویسِ پیامک مقدارهای ممکنِ هر متغیر را از قبل می‌خواهد، و
     متنی که باشگاه‌دار تایپ کند قابلِ اعلام نیست. پس یا از تقویم
     می‌آید، یا از فهرست، یا عدد است. */
  type: 'jalali' | 'select' | 'number'
  /** برای `select` — تنها مقدارهای مجاز */
  options?: string[]
  /** برای `number` — بازه‌ی مجاز */
  min?: number
  max?: number
}

/* ── تاریخ ──
   تقویم `۱۴۰۵/۵/۲۵` می‌دهد؛ همان‌طور در پیامک زشت است و قالبش هم
   قابلِ اعلام نیست. این‌جا به «۲۵ مرداد ۱۴۰۵» درمی‌آید — یک قالبِ
   ثابت که می‌شود در تیکت اعلامش کرد. */
const J_MONTHS = [
  'فروردین', 'اردیبهشت', 'خرداد', 'تیر', 'مرداد', 'شهریور',
  'مهر', 'آبان', 'آذر', 'دی', 'بهمن', 'اسفند',
]
const faDigits = (s: string | number) =>
  String(s).replace(/[0-9]/g, d => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]!)

/** `۱۴۰۵/۵/۲۵` یا `1405/5/25` ← `۲۵ مرداد ۱۴۰۵` */
export function faJalali(raw: string): string {
  const s = String(raw ?? '').replace(/[۰-۹]/g, d => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
  const m = s.match(/^(\d{4})\/(\d{1,2})\/(\d{1,2})$/)
  if (!m) return String(raw ?? '')
  const mo = Number(m[2])
  if (mo < 1 || mo > 12) return String(raw ?? '')
  return `${faDigits(Number(m[3]))} ${J_MONTHS[mo - 1]} ${faDigits(m[1] ?? '')}`
}

