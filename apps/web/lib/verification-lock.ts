/* ─────────────────────────────────────────────────────────────
   قفلِ استعلام‌های پولی — منبعِ واحد.

   هر استعلامِ کد پستی و هر تطبیقِ کارت، اعتبارِ سرویسِ بیرونی را مصرف
   می‌کند. تا پیش از این تنها مانع، حالتِ ری‌اکت در UI بود که با یک
   رفرش از بین می‌رفت و سمتِ سرور اصلاً چک نمی‌شد — یعنی هر کاربر
   می‌توانست بی‌نهایت بار استعلام بگیرد.

   قاعده: یک استعلامِ موفق ⇒ قفل. بازکردنش فقط کارِ ادمین است، پس از
   تیکتِ پشتیبانی. سقفِ نرخ (rate limit) جای این نمی‌نشیند: آن فقط
   سرعت را کم می‌کند، ولی هزینه‌ی تجمعی همچنان بالا می‌رود.

   نکته‌ی مهمِ پیاده‌سازی: چک باید *پیش از* فراخوانِ سرویس انجام شود،
   وگرنه هزینه‌اش را داده‌ایم و بعد جواب را دور ریخته‌ایم.
   ───────────────────────────────────────────────────────────── */

import { NextResponse } from 'next/server'

/** پیامِ یکسان در همه‌جا — کاربر باید بداند دقیقاً چه کند */
export const LOCK_MESSAGES = {
  postal: 'کد پستی این باشگاه قبلاً استعلام و ثبت شده است. برای تغییر آن، از بخش «تماس با ما» با موضوع «درخواست تغییر کد پستی» تیکت بزنید.',
  bank: 'اطلاعات بانکی شما قبلاً استعلام و ثبت شده است. برای تغییر آن، از بخش «تماس با ما» با موضوع «درخواست ویرایش اطلاعات بانکی» تیکت بزنید.',
} as const

/** موضوعِ تیکتی که کاربر باید انتخاب کند — با فهرستِ صفحه‌ی تماس یکی است */
export const LOCK_SUBJECTS = {
  postal: 'درخواست تغییر کد پستی',
  bank: 'درخواست ویرایش اطلاعات بانکی',
} as const

/** پاسخِ استانداردِ «قفل است».
 *
 *  ۴۰۹ (Conflict) نه ۴۰۳: دسترسیِ کاربر مشکلی ندارد، وضعیتِ فعلیِ
 *  منبع است که اجازه‌ی این کار را نمی‌دهد. کلاینت با همین کد
 *  تشخیص می‌دهد که باید کاربر را به پشتیبانی بفرستد. */
export function lockedResponse(kind: keyof typeof LOCK_MESSAGES) {
  return NextResponse.json({
    message: LOCK_MESSAGES[kind],
    locked: true,
    supportSubject: LOCK_SUBJECTS[kind],
  }, { status: 409 })
}

/** آیا ستون هنوز ساخته نشده؟
 *
 *  مهاجرت ۰۳۹ را کاربر دستی اجرا می‌کند. تا وقتی اجرا نشده، نبودِ ستون
 *  نباید کلِ استعلام را بشکند — ولی «نمی‌دانم» را هم نباید «قفل نیست»
 *  ترجمه کرد بی‌آنکه جایی ثبت شود. */
export function isMissingColumn(msg?: string | null): boolean {
  return /column .* does not exist|does not exist|PGRST204|schema cache/i.test(String(msg ?? ''))
}
