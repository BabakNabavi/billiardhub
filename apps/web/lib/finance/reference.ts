/* ─────────────────────────────────────────────────────────────
   شماره‌ی پیگیریِ واریز — چه چیزی را تضمین می‌کند و چه چیزی را نه.

   ── صادقانه ──
   این عدد **استعلام نمی‌شود**. هیچ سرویسی در دسترسِ ما نیست که بپرسد
   «آیا این شماره‌ی پیگیری واقعاً یک انتقالِ انجام‌شده است؟». بانک‌های
   ایران چنین APIای به پذیرنده نمی‌دهند، و مسیرِ تسویه‌ی این پروژه هم
   عمداً «دستی» است (`ManualSettlementProvider`).

   پس این عدد یک **سند** است، نه یک **اثبات**: ادعای ادمین که با نام و
   زمانش در لاگِ ممیزی ثبت می‌شود و موقعِ اختلاف با صورتحسابِ بانک
   مطابقت داده می‌شود.

   ── ولی دو کنترلِ واقعی می‌شود گذاشت ──
   ۱) قالب: عددِ کوتاه یا رشته‌ی بی‌معنی («۱»، «تست»، «۰۰۰۰») تقریباً
      همیشه اشتباهِ تایپی است، نه شماره‌ی واقعی.
   ۲) تکرار: یک شماره‌ی پیگیری به ازای هر انتقال یکتاست. تکرارش یعنی یا
      کپی‌پیستِ اشتباه — که پرداختِ دوم را «انجام‌شده» جا می‌زند — یا
      عددِ ساختگی. این دومی تنها کنترلِ واقعیِ ماست و ارزشش را دارد.
   ───────────────────────────────────────────────────────────── */

const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹'
const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩'

/** ارقامِ فارسی/عربی به لاتین، و حذفِ فاصله و خط تیره */
export function normalizeReference(raw: unknown): string {
  return String(raw ?? '')
    .replace(/[۰-۹]/g, d => String(FA_DIGITS.indexOf(d)))
    .replace(/[٠-٩]/g, d => String(AR_DIGITS.indexOf(d)))
    .replace(/[\s\-_.]/g, '')
    .trim()
    .toUpperCase()
}

/** آیا اصلاً شبیهِ شماره‌ی پیگیریِ بانک است؟
 *
 *  بانک‌های ایران قالبِ واحدی ندارند — بعضی ۶ رقم، بعضی تا ۲۰+ رقم، و
 *  چند تا حرف هم دارند. پس سخت‌گیری بی‌جا فقط جلوی ثبتِ درست را
 *  می‌گیرد. این‌جا فقط چیزهایی رد می‌شوند که قطعاً شماره‌ی پیگیری
 *  نیستند. */
export function referenceProblem(ref: string): string | null {
  if (ref.length < 4) return 'شماره پیگیری خیلی کوتاه است — عدد کاملِ رسید بانکی را وارد کنید'
  if (ref.length > 40) return 'شماره پیگیری خیلی بلند است'
  if (!/^[A-Z0-9]+$/.test(ref)) return 'شماره پیگیری فقط عدد (و در بعضی بانک‌ها حرف انگلیسی) دارد'
  /* «۰۰۰۰۰۰» یا «۱۱۱۱۱۱» — تایپِ سرسری، نه رسید */
  if (/^(.)\1+$/.test(ref)) return 'این عدد معتبر به نظر نمی‌رسد — شماره پیگیری واقعی را وارد کنید'
  return null
}

/* ── تکرار ──
   هر انتقالِ بانکی شماره‌ی پیگیریِ یکتا دارد. اگر همان عدد دوباره ثبت
   شود، یکی از این دو است:

     • کپی‌پیستِ اشتباه — پرداختِ دوم انجام نشده ولی «انجام‌شده» ثبت
       می‌شود، و پولِ طرفِ مقابل بی‌صدا گم می‌شود.
     • عددِ ساختگی.

   هیچ‌کدام را نمی‌شود با استعلام فهمید، ولی هر دو را می‌شود همین‌جا
   گرفت. سه جدول چون سه نوع پرداخت داریم و شماره در هرکدام جای خودش
   ذخیره می‌شود. */
import { sb } from './db'

export interface DuplicateHit { where: string; id: string }

export async function findDuplicateReference(
  ref: string, skip?: { table: string; id: string },
): Promise<DuplicateHit | null> {
  const checks: { table: string; col: string; label: string }[] = [
    { table: 'settlements', col: 'reference_number', label: 'تسویه‌ی باشگاه' },
    { table: 'refunds', col: 'provider_ref', label: 'بازپرداخت رزرو' },
    { table: 'campaign_orders', col: 'refund_reference', label: 'بازپرداخت تبلیغات' },
  ]

  for (const c of checks) {
    try {
      const { data, error } = await sb().from(c.table)
        .select('id').eq(c.col, ref).limit(2)
      /* ستونِ نبوده (مهاجرتِ اجرانشده) نباید جلوی ثبت را بگیرد */
      if (error) continue
      const hit = (data ?? []).find(r =>
        !(skip && skip.table === c.table && skip.id === String((r as { id: string }).id)))
      if (hit) return { where: c.label, id: String((hit as { id: string }).id) }
    } catch { /* جدول نبود — رد شو */ }
  }
  return null
}
