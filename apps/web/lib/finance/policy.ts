/** نرخِ پیش‌فرضِ کمیسیون — **فقط** وقتی استفاده می‌شود که خواندنِ نرخِ
 *  واقعی از دیتابیس ممکن نباشد.
 *
 *  ⚠️ این عدد نرخی نیست که کسر می‌شود. نرخِ واقعی در جدولِ
 *  `commission_rules` است و از پنلِ ادمین عوض می‌شود. تا امروز متنِ
 *  حقوقیِ صفحه‌ی قوانین از همین ثابت ساخته می‌شد، یعنی اگر نرخ عوض
 *  می‌شد، قوانینِ منتشرشده‌ی سایت همچنان ۵٪ می‌گفت — و همان متن چیزی
 *  است که باشگاه‌دار در اختلاف به آن استناد می‌کند.
 *
 *  `lib/finance/rates.ts` نرخِ زنده را می‌خواند؛ این‌جا فقط تکیه‌گاهِ
 *  آخر است. */
export const PLATFORM_FEE_PERCENT = 5

/** یک نرخِ کمیسیون، همان‌طور که در دیتابیس ذخیره شده */
export interface FeeRate { type: 'PERCENTAGE' | 'FIXED_AMOUNT'; value: number }

const feeText = (r: FeeRate) =>
  r.type === 'FIXED_AMOUNT'
    ? `${r.value.toLocaleString('fa-IR')} تومان`
    : `${r.value.toLocaleString('fa-IR')} درصد`

/** بندهای «کمیسیون خدمات» با نرخِ واقعیِ امروز.
 *  بدونِ آرگومان، نرخِ پیش‌فرض را می‌گذارد. */
export function feeRules(
  reservation: FeeRate = { type: 'PERCENTAGE', value: PLATFORM_FEE_PERCENT },
  tournament: FeeRate = { type: 'PERCENTAGE', value: PLATFORM_FEE_PERCENT },
): string[] {
  return [
    `در ازای هر رزرو موفق، ${feeText(reservation)} از مبلغ رزرو به‌عنوان کمیسیون خدمات به بیلیارد هاب تعلق می‌گیرد.`,
    `در ازای هر ثبت‌نام موفق در مسابقات، ${feeText(tournament)} از مبلغ ورودی به‌عنوان کمیسیون خدمات به بیلیارد هاب تعلق می‌گیرد.`,
    /* این بند صریح نوشته می‌شود چون منبع رایج سوءتفاهم است: باشگاه‌دار
       نرخ را می‌بیند و انتظار دارد بقیه‌ی مبلغ دقیقا به حسابش بنشیند. */
    'کارمزد درگاه پرداخت جدا از کمیسیون بیلیارد هاب است و توسط شرکت پرداخت‌یار دریافت می‌شود؛ این مبلغ سهم بیلیارد هاب نیست.',
  ]
}

