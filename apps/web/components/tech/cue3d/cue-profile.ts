/* ─────────────────────────────────────────────────────────────
   نیم‌رخِ چوبِ بیلیارد برای هندسه‌ی دورانی.

   ── چرا دورانی (lathe) ──
   چوبِ بیلیارد **واقعاً** روی تراش ساخته می‌شود: یک نیم‌رخ که حولِ
   محور می‌چرخد. پس این مدلِ سه‌بعدی تقریبِ یک استوانه نیست — همان
   عملیاتی است که چوب را در دنیای واقعی می‌سازد. به همین دلیل هم
   «شیءِ سه‌بعدیِ جایگزینِ زشت» از آب درنمی‌آید.

   ── واحد ──
   یک واحد = ۱۰ سانتی‌متر. چوبِ استانداردِ ۱۴۷ سانتی ⟵ ۱۴٫۷ واحد.
   شعاع‌ها از قطرهای واقعی می‌آیند: تیپ ۱۳mm، بات ۳۰mm.

   ⚠️ هر قطعه نقطه‌ی مرزیِ همسایه‌اش را *تکرار* می‌کند. اگر تکرار
   نشود، بینِ دو جنسِ مختلف یک درزِ نازک دیده می‌شود که در نمای
   ماکرو داد می‌زند.
   ───────────────────────────────────────────────────────────── */

/** یک نقطه‌ی نیم‌رخ: [شعاع، فاصله از نوکِ تیپ] */
export type ProfilePoint = readonly [r: number, y: number]

export interface CueSection {
  id: string
  /** نامِ فارسی — برای برچسبِ ایستگاه */
  label: string
  points: readonly ProfilePoint[]
}

