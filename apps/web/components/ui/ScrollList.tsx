'use client'

/* ─────────────────────────────────────────────────────────────
   فهرستِ قاب‌دار با اسکرولِ داخلی.

   ── مشکلی که این را ساخت ──
   صفحه‌های پنلِ ادمین ردیف‌ها را همین‌طور زیرِ هم می‌ریختند. با ده
   کاربر خوب به‌نظر می‌رسید؛ با پانصد کاربر صفحه چند ده هزار پیکسل
   بلند می‌شد و هرچه پایینِ فهرست بود — دکمه‌ها، صفحه‌بندی، بخشِ
   بعدی — عملاً ناپیدا می‌شد. اسکرولِ صفحه هم هیچ‌وقت به ته
   نمی‌رسید.

   ── چرا سقفِ ارتفاع و نه «۱۵ ردیفِ اول» ──
   ردیف‌ها ارتفاعِ یکسان ندارند: کارتِ یک تیکت با پاسخِ بلند چند
   برابرِ یک ردیفِ کاربر است. شمردنِ ردیف یعنی یک فهرست کوتاه و
   دیگری همچنان بی‌انتها. سقف بر حسبِ ارتفاع، هر دو را یک‌اندازه
   نگه می‌دارد.

   ── چرا فقط وقتی لازم است قاب می‌گیرد ──
   فهرستِ سه‌ردیفی نباید اسکرول‌بار و قابِ بی‌دلیل داشته باشد. زیرِ
   `min`، کامپوننت عملاً یک `<div>` ساده است.
   ───────────────────────────────────────────────────────────── */

export default function ScrollList({
  count, min = 6, maxHeight = 'min(62vh, 540px)', gap = 10, children, style, className,
}: {
  /** تعدادِ ردیف‌ها — تصمیمِ «قاب لازم است یا نه» با همین گرفته می‌شود */
  count: number
  /** زیرِ این تعداد، هیچ قابی گذاشته نمی‌شود */
  min?: number
  maxHeight?: string
  gap?: number
  children: React.ReactNode
  style?: React.CSSProperties
  /** برای صفحه‌هایی که با Tailwind نوشته شده‌اند (مثلِ مدیریتِ کاربران) */
  className?: string
}) {
  const bounded = count > min
  return (
    <div className={className} style={{
      display: 'flex', flexDirection: 'column', gap,
      ...(bounded ? {
        maxHeight, overflowY: 'auto',
        /* فاصله‌ی کوچک تا ردیفِ آخر به اسکرول‌بار نچسبد */
        paddingInlineEnd: 6,
        scrollbarWidth: 'thin' as const,
      } : null),
      ...style,
    }}>
      {children}
    </div>
  )
}
